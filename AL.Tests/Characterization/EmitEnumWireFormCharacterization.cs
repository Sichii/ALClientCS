    }

    [TestMethod]
    public void T7_Stand_Emit_Throws()
    {
        //FalsyConverter<Stand>.WriteJson is unimplemented; Stand is an inbound-only field and is never emitted
        Assert.ThrowsException<NotImplementedException>(() => JsonConvert.SerializeObject(Stand.Stand));
        Assert.ThrowsException<NotImplementedException>(() => JsonConvert.SerializeObject(new Box<Stand> { V = Stand.Stand }));
    }

    [TestMethod]
    public void T7_ALClass_Emit_Throws()
    {
        //ALClassConverter.WriteJson is unimplemented; ALClass is an inbound-only field and is never emitted
        Assert.ThrowsException<NotImplementedException>(() => JsonConvert.SerializeObject(ALClass.Mage));
        Assert.ThrowsException<NotImplementedException>(() => JsonConvert.SerializeObject(new Box<ALClass> { V = ALClass.Mage }));
    }

    [TestMethod]
    public void T7_StringEnums_DeserializeBackFromEveryEmittedWireForm()
    {
        //round-trip: every member that emits a string must deserialize back to itself
        AssertRoundTrips<Slot>();
        AssertRoundTrips<TradeSlot>();
        AssertRoundTrips<BankPack>();
        AssertRoundTrips<WeaponType>();
    }

    private static void AssertRoundTrips<T>() where T: struct, Enum
    {
        foreach (var name in Enum.GetNames<T>())
        {
            var value = Enum.Parse<T>(name);
            var bare = JsonConvert.SerializeObject(value);

            Assert.AreEqual(value, JsonConvert.DeserializeObject<T>(bare), $"{typeof(T).Name}.{name} did not round-trip from {bare}.");
        }
    }

    [TestMethod]
    public void T7_Stand_DeserializesFromLowercaseWireForm()
    {
        //the server sends the lowercase member name; the FalsyConverter matches it case-insensitively
        Assert.AreEqual(Stand.Stand, JsonConvert.DeserializeObject<Stand>(@"""stand"""));
        Assert.AreEqual(Stand.CStand, JsonConvert.DeserializeObject<Stand>(@"""cstand"""));
        Assert.AreEqual(Stand.Stand0, JsonConvert.DeserializeObject<Stand>(@"""stand0"""));
        Assert.AreEqual(Stand.Stand1, JsonConvert.DeserializeObject<Stand>(@"""stand1"""));

        //"false" (the falsy wire form) degrades to the default
        Assert.AreEqual(Stand.None, JsonConvert.DeserializeObject<Stand>("false"));
    }

    [TestMethod]
    public void T7_ALClass_DeserializesFromWireForm()
    {
        Assert.AreEqual(ALClass.Mage, JsonConvert.DeserializeObject<ALClass>(@"""mage"""));
        Assert.AreEqual(ALClass.Merchant, JsonConvert.DeserializeObject<ALClass>(@"""merchant"""));
        Assert.AreEqual(ALClass.Warrior, JsonConvert.DeserializeObject<ALClass>(@"""warrior"""));

        //null degrades to the zero member
        Assert.AreEqual(ALClass.None, JsonConvert.DeserializeObject<ALClass>("null"));
    }

    [TestMethod]
    public void T7_UnknownValue_DegradesToZeroMember()
    {
        //the tolerant converter defaults an unrecognized wire value to the enum's zero member rather than throwing
        Assert.AreEqual(Slot.None, JsonConvert.DeserializeObject<Slot>(@"""nonexistent_slot"""));
        Assert.AreEqual(TradeSlot.None, JsonConvert.DeserializeObject<TradeSlot>(@"""nonexistent_slot"""));
        Assert.AreEqual(BankPack.None, JsonConvert.DeserializeObject<BankPack>(@"""nonexistent_pack"""));
        Assert.AreEqual(WeaponType.None, JsonConvert.DeserializeObject<WeaponType>(@"""nonexistent_weapon"""));
        Assert.AreEqual(Stand.None, JsonConvert.DeserializeObject<Stand>(@"""nonexistent_stand"""));
    }

    [TestMethod]
    public void T7_ALClass_UnknownValue_DegradesToNpc_NotZero()
    {
        //ALClassConverter is the one exception: an unrecognized class becomes NPC (8), not the zero member None -
        //the server treats an unknown entity as an NPC, so this is deliberate, but it breaks the "degrades to
        //zero" invariant the other five enums hold
        Assert.AreEqual(ALClass.NPC, JsonConvert.DeserializeObject<ALClass>(@"""nonexistent_class"""));
        Assert.AreNotEqual(ALClass.None, JsonConvert.DeserializeObject<ALClass>(@"""nonexistent_class"""));
    }
}

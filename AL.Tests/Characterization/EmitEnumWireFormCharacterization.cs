    [TestMethod]
    public void T7_WeaponType_EmitsMemberNameHonoringEnumMember_BareAndInObject()
    {
        //no naming strategy here, so the wire form is the CLR name, except where [EnumMember] overrides it
        Assert.AreEqual(@"""None""", JsonConvert.SerializeObject(WeaponType.None));
        Assert.AreEqual(@"""Axe""", JsonConvert.SerializeObject(WeaponType.Axe));
        Assert.AreEqual(@"""great_staff""", JsonConvert.SerializeObject(WeaponType.GreatStaff));
        Assert.AreEqual(@"""great_sword""", JsonConvert.SerializeObject(WeaponType.GreatSword));
        Assert.AreEqual(@"""misc_offhand""", JsonConvert.SerializeObject(WeaponType.MiscOffhand));

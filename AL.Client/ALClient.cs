    /// <summary>
    ///     Asynchronously connects to an Adventure.Land socket server.
    /// </summary>
    /// <param name="region">
    ///     The region to connect to.
    /// </param>
    /// <param name="identifier">
    ///     The identifier within the region to connect to.
    /// </param>
    /// <exception cref="InvalidOperationException">
    ///     There is already an open socket in use. Try disposing it and reconnecting.
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Character ""{Name}"" not found.
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Server {region} {identifier} not found."
    /// </exception>
    public async Task ConnectAsync(ServerRegion region, ServerId identifier)
    {
        if (Socket.Connected)
            throw new InvalidOperationException("There is already an open socket in use. Try disposing it and reconnecting.");

        var serversAndCharacters = await API.GetServersAndCharactersAsync();
        var charInfo = serversAndCharacters.Characters.FirstOrDefault(character => character.Name.EqualsI(Name));

        var serverInfo
            = serversAndCharacters.Servers.FirstOrDefault(server => (server.Region == region) && (server.Identifier == identifier));

        if (charInfo == null)
            throw new InvalidOperationException($@"Character ""{Name}"" not found.");

        Identifier = charInfo.Id;
        Server = serverInfo ?? throw new InvalidOperationException($@"Server {region} {identifier} not found.");

        await using var @lock = await Sync.WaitAsync();
        await InternalConnectAsync();
    }

    /// <summary>
    ///     Moves this character to another server without rebuilding the client. The socket is replaced and
    ///     <see cref="OnReconnected" /> is raised, which is the road an automatic reconnect already takes - so a
    ///     consumer that re-registers its subscriptions on that event needs no second code path for this.
    ///     <br />
    ///     <see cref="LoggedIn" /> is false for the whole swap, so anything gating work on it stands down and picks
    ///     itself back up. What the character owns travels with it: inventory, gold, the bank and the position are on
    ///     the character's own record rather than on the server it was last seen from.
    /// </summary>
    /// <remarks>
    ///     The intentional disconnect is what keeps the automatic reconnect out of this. <c>ALSocketClient</c> clears
    ///     its <c>Connected</c> flag before the transport drops, so its own handler suppresses
    ///     <see cref="OnDisconnected" /> and nothing races us back to the server we are leaving.
    ///     <br />
    ///     What is <b>not</b> guarded is a genuine drop landing in the same moment. <see cref="ReconnectAsync" /> takes
    ///     no lock, so both would be assigning <see cref="Socket" /> and the last writer decides where the character
    ///     ends up. Nothing here can detect that; a caller that cares should re-read <see cref="Server" /> afterwards
    ///     and ask again. Closing it properly means putting <see cref="ReconnectAsync" /> under <c>Sync</c> too, which
    ///     is a wider change than this one.
    ///     <br />
    ///     A refused login on the far server throws, leaving the client holding a socket that never authenticated and
    ///     <see cref="LoggedIn" /> false. Deliberately not handled here - the socket we came from is already gone, so
    ///     there is nothing to fall back to at this level. The caller decides.
    /// </remarks>
    /// <exception cref="InvalidOperationException">
    ///     Server {region} {identifier} not found.
    /// </exception>
    public async Task ChangeServerAsync(ServerRegion region, ServerId identifier)
    {
        await using var @lock = await Sync.WaitAsync();

        if ((Server.Region == region) && (Server.Identifier == identifier))
            return;

        //resolved before anything is torn down, so a server this account cannot see costs the lookup and nothing else
        var serversAndCharacters = await API.GetServersAndCharactersAsync();

        var serverInfo = serversAndCharacters.Servers.FirstOrDefault(
                             server => (server.Region == region) && (server.Identifier == identifier))
                         ?? throw new InvalidOperationException($@"Server {region} {identifier} not found.");

        Logger.Warn($"Changing server to {serverInfo.Key}");

        LoggedIn = false;

        //stopped ahead of the socket for the reason DisconnectAsync stops them there: the suppressed OnDisconnected
        //never runs, so these two would go on polling a closed socket and log an EmitAsync throw every tick
        await PingManager.StopAsync();
        await EntityManager.StopAsync();

        try
        {
            await Socket.DisconnectAsync();
        } catch
        {
            //ignored - the socket we are leaving is unreachable either way
        }

        Server = serverInfo;

        //a fresh one rather than the old one reconnected: ALSocketClient disposes its inner socket on disconnect and
        //refuses to open again, which is why the reconnect path builds one too
        Socket = new ALSocketClient(new FormattedLogger(Name, LogManager.GetLogger<ALSocketClient>()));

        await InternalConnectAsync();

        try
        {
            OnReconnected?.Invoke(this, EventArgs.Empty);
        } catch (Exception e)
        {
            //a subscriber's failure is not a failed change of server - the socket is live and authenticated
            Logger.Error($"OnReconnected subscriber threw. {e}");
        }
    }

    /// <summary>
    ///     Builds a character client of the requested type and logs it in. Every character class's StartAsync is this,
    ///     differing only in which type <paramref name="createClient" /> constructs.
    /// </summary>
    protected private static async Task<T> StartClientAsync<T>(
        string characterName,
        ServerRegion region,
        ServerId identifier,
        IAlApiClient apiClient,
        Func<string, IAlApiClient, IALSocketClient, T> createClient) where T: ALClient
    {
        if (string.IsNullOrEmpty(characterName))
            throw new ArgumentNullException(nameof(characterName));

        ArgumentNullException.ThrowIfNull(apiClient);

        var logger = new FormattedLogger(characterName, LogManager.GetLogger<ALSocketClient>());
        var socketClient = new ALSocketClient(logger);
        var client = createClient(characterName, apiClient, socketClient);

        await client.ConnectAsync(region, identifier);

        return client;
    }

    protected async Task InternalConnectAsync()
    {
        LoggedIn = false;
        AttachListeners();

        var source = new TaskCompletionSource<Expectation<StartData>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameErrorCallback = Socket.On<GameMessageData>(
            ALSocketMessageType.GameError,
            data => Task.FromResult(source.TrySetResult(data.Message)));

        using var gameLogCallback = Socket.On<GameMessageData>(
            ALSocketMessageType.GameLog,
            data =>
            {
                //the auth handler answers two rejection paths with game_log, not game_error (node/server.js:
                //10307,10310,10313). Fail the handshake fast on exactly those so the reconnect loop reacts at
                //once rather than waiting out the login timeout. game_log is also the channel for benign in-game
                //notices (loot, kills, purchases), so match the specific messages - never abort login on any
                //game_log. "Authorization in progress." is transient (dc_players clears within ~24s and a retry
                //succeeds); "Wrong passphrase!" is terminal.
                if (data.Message.EqualsI("Authorization in progress."))
                    source.TrySetResult(data.Message);
                else if (data.Message.EqualsI("Wrong passphrase!"))
                {
                    FatalError = "wrong_passphrase";
                    source.TrySetResult(data.Message);
                }

                return TaskCache.FALSE;
            });

        using var welcomeCallback = Socket.On<WelcomeData>(
            ALSocketMessageType.Welcome,
            async _ =>
            {
                //dont await, seems to cause issues
                await Socket.EmitAsync(
                    ALSocketEmitType.Auth,
                    new
                    {
                        auth = API.Auth.AuthKey,
                        character = Identifier,
                        height = 1080,
                        no_graphics = "true",
                        no_html = "1",
                        passphrase = string.Empty,
                        scale = 2,
                        user = API.Auth.UserID,
                        width = 1920
                    });

                return false;
            });

        using var startCallback = Socket.On<StartData>(
            ALSocketMessageType.Start,
            data =>
            {
                source.TrySetResult(data);

                return TaskCache.FALSE;
            });

        //timed out for the same reason the handshake below is: without one, a connect that never completes never
        //throws either, so ReconnectAsync's retry loop never runs, FatalError is never set, and nothing anywhere
        //learns the character is down. The socket is left open on a timeout - ReconnectAsync disposes it.
        await Socket.ConnectAsync(Server)
                    .WithTimeout(10000);

        var result = await source.Task.WithTimeout(10000);
        result.ThrowIfUnsuccessful();

        Socket.OnDisconnected += OnDisconnected;
        EntityManager.Start();
        PingManager.Start();
        LoggedIn = true;
    }


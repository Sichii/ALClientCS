    /// <summary>
    ///     Invoked once immediately before a recall is emitted, if set. A consumer's chance to arrange whatever has to
    ///     be true before the three second channel starts.
    /// </summary>
    /// <remarks>
    ///     Anything that hits the character deletes every channel it has, and so does equipping an item, so a defence
    ///     against either has to be standing before the emit - there is no point inside the channel at which it can be
    ///     arranged. This is the one seam every recall passes through, a pathfound one included.
    ///     <br />
    ///     Awaited, so the recall waits on it and a hook that throws takes the recall down with it.
    /// </remarks>
    public Func<CancellationToken, Task>? BeforeTownRecall { get; set; }

    /// <summary>
    ///     True from the moment a recall is emitted until it has landed, been refused, or been given up on.
    /// </summary>
    /// <remarks>
    ///     <c>Character.Channeling</c> carries the recall only once the server has
    ///     answered for it, so anything reading that to decide whether to stand down is blind for the round trip
    ///     after the emit - and an attack, a drink or an equip landing inside that window empties the whole channel
    ///     dictionary on the server before the client ever knew there was one to protect. That is a cancellation the
    ///     character causes itself, and it reads as a recall failing for no reason.
    ///     <br />
    ///     This is the same question asked about intent rather than about confirmation, so it covers the window as
    ///     well. Not raised until <see cref="BeforeTownRecall" /> has returned, since the cover that hook arranges is
    ///     itself a cast that would stand down against it.
    /// </remarks>
    public bool IsRecalling { get; private set; }

    /// <summary>
    ///     Asynchronously uses the town ability to go to spawn index 0 on the current map.
    /// </summary>
    /// <param name="token">
    ///     A token used to cancel this action.
    /// </param>
    /// <returns>
    ///     <see cref="NewMapData" />
    ///     <br />
    ///     The data for the map after this action has completed or been canceled.
    /// </returns>
    public async Task UseTownAsync(CancellationToken? token = null)
    {
        //before anything else this method sets up: the hook is allowed to spend time, and a callback registered
        //around it would be listening through frames belonging to whatever it does. Ahead of IsRecalling as well,
        //since the cover the hook arranges is itself a cast the flag would stand down
        if (BeforeTownRecall is not null)
            await BeforeTownRecall(token ?? CancellationToken.None);

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        var warpBegin = false;

        //read before the emit: the frame handler below has already merged the incoming counter onto Character by
        //the time our callback runs, so the comparison has to be against where we started
        var mapChangeCountAtStart = Character.MapChangeCount;

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                // ReSharper disable once ConvertIfStatementToSwitchStatement
                if (!warpBegin && (data.Channeling != null) && data.Channeling.ContainsKey("town"))
                    warpBegin = true;

                //the channel ending is not the same thing as the channel being interrupted - the server deletes it
                //and then transports, so a recall that lands also produces a frame with no channel on it. The map
                //change is what tells the two apart, and it is stamped before either of the completion frames goes
                //out. Without it this raced the new_map carrying the whole entity list, lost every time because a
                //player frame is a fraction of the size, and reported a landed recall as canceled
                else if (warpBegin
                         && (data.Channeling?.ContainsKey("town") != true)
                         && (data.MapChangeCount == mapChangeCountAtStart))
                    source.TrySetResult("Failed to town. (canceled)");

                return TaskCache.FALSE;
            });

        using var newMapCallback = Socket.On<NewMapData>(
            ALSocketMessageType.NewMap,
            data =>
            {
                if (warpBegin && (data.Effect == DisappearEffect.Town))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                //cant_escape is the tank's refusal: the server refuses a recall while more than five things are
                //targeting you. Without an arm here it matched nothing, so a character holding aggro burned the whole
                //timeout on every attempt and never fell back to walking
                if (data.ResponseType is GameResponseType.TransportFailed)
                    source.TrySetResult("Failed to town. (failed)");
                else if (data.ResponseType is GameResponseType.CantEscape)
                    source.TrySetResult("Failed to town. (can't escape)");

                return TaskCache.FALSE;
            });

        //raised before the emit rather than off the server's answer, which is the whole reason it exists
        IsRecalling = true;

        //for the cancellation line below, which is the only place the elapsed channel is visible
        var channelStarted = System.Diagnostics.Stopwatch.GetTimestamp();

        try
        {
            await Socket.EmitAsync(ALSocketEmitType.ReturnToTown);

            //disposed with the call: an undisposed registration outlives the recall it was for and fires on whatever
            //cancels that token next, stopping a town nobody is channeling and logging the cancellation of a recall
            //that landed minutes ago
            using var cancelRegistration = token?.Register(
                () =>
                {
                    _ = Socket.EmitAsync(
                        ALSocketEmitType.Stop,
                        new
                        {
                            action = "town"
                        });
                    //how far in it got, because that is what separates a caller that changed its mind from one whose
                    //own poll interval is shorter than the channel and so can never let one land
                    Logger.Info($"Town recall canceled {System.Diagnostics.Stopwatch.GetElapsedTime(channelStarted).TotalMilliseconds:F0}ms into the channel");
                    source.TrySetResult(Expectation.Success);
                })
                              ?? default;

            var expectation = await source.Task.WithTimeout(5000);
            expectation.ThrowIfUnsuccessful();
        } finally
        {
            IsRecalling = false;
        }
    }

    /// <summary>
    ///     Asynchronously withdraws gold from the bank.
    /// </summary>
    /// <param name="amount">
    ///     The amount of gold to withdraw
    /// </param>
    /// <exception cref="InvalidOperationException">
    ///     Failed to withdraw {amount} gold. ({reason})
    /// </exception>
    public async Task WithdrawGoldAsync(long amount)
    {
        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to withdraw {amount} gold. (not in bank)");

        var shouldChange = (amount > 0) && (Bank!.Gold > 0);

        if (!shouldChange || (amount > Bank!.Gold))
            throw new InvalidOperationException($"Failed to withdraw {amount} gold. (invalid amount)");

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);
        var previousGold = Character.Gold;

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    source.TrySetResult($"Failed to withdraw {amount} gold. (not in bank)");

                var didChange = !previousGold.IsNear(data.Gold, CORE_CONSTANTS.EPSILON);

                if (shouldChange && didChange)
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                amount,
                operation = "withdraw"
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>
    ///     Asynchronously withdraws an item from the bank.
    /// </summary>
    /// <param name="bankPack">
    ///     The bankPack to withdraw from.
    /// </param>
    /// <param name="bankSlot">
    ///     The slot within the bankPack to withdraw from.
    /// </param>
    /// <param name="inventorySlot">
    ///     The slot in the inventory to place the item. -1 for first available.
    /// </param>
    /// <returns>
    ///     <see cref="InventoryIndexer" />
    ///     <br />
    ///     Information about the withdrawn item in the inventory.
    /// </returns>
    /// <exception cref="InvalidOperationException">
    ///     Failed to withdraw item {item}. ({reason})
    /// </exception>
    public async Task<InventoryIndexer> WithdrawItemAsync(BankPack bankPack, int bankSlot, int inventorySlot = -1)
    {
        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to withdraw item {bankPack}:{bankSlot}. (not in bank)");

        var availableBanks = GetAvailableBankPacks();

        if (!availableBanks.Contains(bankPack) || !Bank!.TryGetValue(bankPack, out var bankedItems))
            throw new InvalidOperationException($"Failed to withdraw item {bankPack}:{bankSlot}. (wrong bank)");

        var item = bankedItems[bankSlot];

        if (item == null)
            throw new InvalidOperationException($"Failed to withdraw item {bankPack}:{bankSlot}. (no item)");

        var source = new TaskCompletionSource<Expectation<InventoryIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if (data.ResponseType == GameResponseType.Invalid)
                    source.TrySetResult($"Failed to withdraw item {item.Name}. (invalid)");

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    source.TrySetResult($"Failed to withdraw item {bankPack}:{bankSlot}. (not in bank)");

                var inventoryItem = data.Inventory[inventorySlot];

                if (inventoryItem != null)
                    source.TrySetResult(
                        new InventoryIndexer
                        {
                            Index = inventorySlot,
                            Item = inventoryItem
                        });

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "swap",
                inv = inventorySlot,
                str = bankSlot,
                pack = bankPack.ToString()
                               .ToLower()
            });

        return await source.Task.WithNetworkTimeout();
    }

    /// <summary>
    ///     Asynchronously withdraws an item from the bank without naming a destination, so the server picks the
    ///     landing slot and folds the item into a stack the inventory already holds.
    /// </summary>
    /// <param name="bankPack">
    ///     The bankPack to withdraw from.
    /// </param>
    /// <param name="bankSlot">
    ///     The slot within the bankPack to withdraw from.
    /// </param>
    /// <returns>
    ///     The inventory slot the item landed in - an existing stack's slot whenever it merged.
    /// </returns>
    /// <remarks>
    ///     <see cref="WithdrawItemAsync" /> cannot do this: naming <c>inv</c> takes the server's raw swap branch,
    ///     which assigns the slot outright, where an unnamed one takes the pull branch and its <c>add_item</c>
    ///     (<c>node/server.js:8548</c>). That merge is what puts a whole quantity in the one slot a craft or an
    ///     exchange reads it from, and it needs no free slot at all when a stacking partner is held
    ///     (<c>js/old_common_functions.js:405</c>). The cost is that the reserved-range discipline a caller gets by
    ///     naming the slot does not apply - the server merges into the first partner it finds, reserved or not.
    /// </remarks>
    /// <exception cref="InvalidOperationException">
    ///     Failed to withdraw item {item}. ({reason})
    /// </exception>
    public async Task<int> WithdrawItemMergingAsync(BankPack bankPack, int bankSlot)
    {
        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to withdraw item {bankPack}:{bankSlot}. (not in bank)");

        var availableBanks = GetAvailableBankPacks();

        if (!availableBanks.Contains(bankPack) || !Bank!.TryGetValue(bankPack, out var bankedItems))
            throw new InvalidOperationException($"Failed to withdraw item {bankPack}:{bankSlot}. (wrong bank)");

        var item = bankedItems[bankSlot];

        if (item == null)
            throw new InvalidOperationException($"Failed to withdraw item {bankPack}:{bankSlot}. (no item)");

        var source = new TaskCompletionSource<Expectation<int>>(TaskCreationOptions.RunContinuationsAsynchronously);

        //the game_response is the only frame that can settle this. The character frame the server sends first
        //(node/server.js:8556) carries no slot number, and the destination is not known here to watch one - that is
        //the whole point of the operation. Both outcomes land on this message: the landing slot in inv, or the
        //refusal, and place names the socket method either was answered from (node/server_functions.js:2827, :2855)
        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if (data.Place?.EqualsI("bank") != true)
                    return TaskCache.FALSE;

                //the server echoes str on every item branch of this handler and on none of the gold ones, so a
                //frame naming a different bank slot is another operation's answer. A refusal names no slot at all
                //and so settles on place alone, which is right: two bank refusals are the same outcome either way
                if ((data.BankSlot is { } answered) && (answered != bankSlot))
                    return TaskCache.FALSE;

                if (data.Failed)
                    source.TrySetResult($"Failed to withdraw item {item.Name}. ({data.ResponseType})");
                else if (data.Success)
                    source.TrySetResult(
                        data.InventorySlot is { } landed
                            ? new Expectation<int>(landed)

                            //the bank slot was already empty by the time the emit landed: the server answers success
                            //having moved nothing, so this is the refusal rather than a whole timeout spent waiting
                            //for a frame that is never coming
                            : new Expectation<int>($"Failed to withdraw item {item.Name}. (nothing in {bankPack}:{bankSlot})"));

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "swap",
                str = bankSlot,
                pack = bankPack.ToString()
                               .ToLower()
            });

        return await source.Task.WithNetworkTimeout();
    }

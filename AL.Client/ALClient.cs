    protected Task<bool> OnGameResponseAsync(GameResponseData data)
    {
        if (!data.ContainsData)
            return TaskCache.FALSE;

        // ReSharper disable once SwitchStatementMissingSomeEnumCasesNoDefault
        switch (data.ResponseType)
        {
            case GameResponseType.Cooldown:
            {
                SetCooldown(data.SkillName ?? data.Place!, data.CooldownMS);

                break;
            }
            case GameResponseType.ConditionExpired:
            {
                if (EnumHelper.TryParse(data.Name, out Condition conditionName))
                    Character.Conditions.Remove(conditionName, out _);

                break;
            }

            //the generic skill success is {response:"data", place:<skill>, success:true} - no skill, no name
            case GameResponseType.Data when data.Success && !string.IsNullOrEmpty(data.Place):
            {
                if (IsOffCooldown(data.Place))
                    SetCooldown(data.Place);

                break;
            }
        }

        return TaskCache.FALSE;
    }

    protected Task<bool> OnHitAsync(HitData data)
    {
        if (!string.IsNullOrEmpty(data.ProjectileId) && Projectiles.TryGetValue(data.ProjectileId, out var projectile))
        {
            Projectiles.Remove(data.ProjectileId, out _);

            if ((data.Reflect != 0) && !string.IsNullOrEmpty(projectile.ProjectileId))
            {
                var newProjectile = projectile with
                {
                    Damage = data.Reflect,
                    Target = data.HitId,
                    X = Character.X,
                    Y = Character.Y
                };

                Projectiles.AddOrUpdate(newProjectile.ProjectileId, newProjectile, (_, _) => newProjectile);
            }
        }

        if (data.Kill)
            DestroyEntity(data.Id);
        else if (data.Damage != 0)
        {
            var entity = GetEntity(data.Id);
            entity?.Mutate(new Mutation(ALAttribute.Hp, -data.Damage));
        }

        if (data.Reflect != 0)
        {
            //the reflect shape omits "source", and "source" is the attack type rather than an id anyway.
            //"hid" is the attacker, which is who takes the reflected damage.
            var sourceEntity = GetEntity(data.HitId);
            sourceEntity?.Mutate(new Mutation(ALAttribute.Hp, -data.Reflect));
        }

        return TaskCache.FALSE;
    }


    protected ALClient(string characterName, IAlApiClient apiClient, IALSocketClient socketClient)
    {
        if (string.IsNullOrEmpty(characterName))
            throw new ArgumentNullException(nameof(characterName));

        Name = characterName;
        Logger = new FormattedLogger(characterName, LogManager.GetLogger<ALClient>());
        AchievementProgress = new ConcurrentDictionary<string, AchievementProgressData>();
        API = apiClient ?? throw new ArgumentNullException(nameof(apiClient));
        Monsters = new ConcurrentDictionary<string, Monster>();
        Players = new ConcurrentDictionary<string, Player>();
        Projectiles = new ConcurrentDictionary<string, ActionData>();
        BaseGold = new Dictionary<string, IReadOnlyDictionary<string, int>>();
        Cooldowns = new ConcurrentDictionary<string, CooldownInfo>(StringComparer.OrdinalIgnoreCase);
        Emotion = new Dictionary<Emotion, float>();
        EventsAndBosses = new EventAndBossInfo();
        Friends = new List<string>();
        OwnedCosmetics = new Dictionary<string, int>();
        Chests = new ConcurrentDictionary<string, DropData>();
        Socket = socketClient ?? throw new ArgumentNullException(nameof(socketClient));
        Server = null!;

        Character = new Character();

        //two boxes, because the game uses two: the small foot-print everything walks and pathfinds with, and the whole
        //sprite that range is resolved against
        Character.SetBoundingBase(PATHFINDING_CONSTANTS.DEFAULT_BOUNDING_BASE);
        Character.SetHitBox(GameData.DEFAULT_CHARACTER_HIT_BOX);

        PingManager = new PingManager(this);
        EntityManager = new EntityManager(this);

        //on the re-raised event rather than the socket's, so the meter keeps counting through a reconnect
        CallMeter = new CallMeter();
        OnEmit += (_, emitType) => CallMeter.Record(emitType);
    }

    public async ValueTask DisposeAsync() => await DisconnectAsync();

    /// <inheritdoc />
    public void Update(TimeSpan delta)
    {
        foreach (var kvp in Cooldowns.ToList())
        {
            kvp.Value.Update(delta);

            if (kvp.Value.CanUse())
                Cooldowns.Remove(kvp.Key, out _);
        }

        foreach (var projectile in Projectiles.Values.ToList())
            if (projectile.Created.AddMilliseconds(projectile.ETA) < DateTime.UtcNow)
                Projectiles.Remove(projectile.ProjectileId!, out _);

        Character.Update(delta);
    }


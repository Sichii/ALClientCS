    /// <summary>
    ///     Asynchronously swaps the items between two bank slots, or moves an item from one slot to another.
    /// </summary>
    /// <param name="bankPack">The bankpack whose slots are to be swapped.</param>
    /// <param name="bankSlot1">A slot index within the inventory.</param>
    /// <param name="bankSlot2">A slot index within the inventory.</param>
    /// <exception cref="ArgumentOutOfRangeException">bankSlot1</exception>
    /// <exception cref="ArgumentOutOfRangeException">bankSlot2</exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to swap bank slots {bankSlot1} and {bankSlot2}. ({reason})
    /// </exception>
    public async Task SwapBankSlotsAsync(BankPack bankPack, int bankSlot1, int bankSlot2)
    {
        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to swap bank slots {bankSlot1} and {bankSlot2}. (not in bank)");

        if (!Character.Bank.TryGetValue(bankPack, out var bank))
            throw new InvalidOperationException($"Failed to swap bank slots {bankSlot1} and {bankSlot2}. (bank unavailable)");

        if ((uint)bankSlot1 >= BANK_PACK_SIZE)
            throw new ArgumentOutOfRangeException(nameof(bankSlot1));

        if ((uint)bankSlot2 >= BANK_PACK_SIZE)
            throw new ArgumentOutOfRangeException(nameof(bankSlot2));

        //the server refuses a == b outright, and there is nothing to move
        if (bankSlot1 == bankSlot2)
            return;

        var item1 = GetItem(bank, bankSlot1);
        var item2 = GetItem(bank, bankSlot2);

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if (data.Failed && "bank".EqualsI(data.Place!))
                    source.TrySetResult($"Failed to swap bank slots {bankSlot1} and {bankSlot2}. ({data.ResponseType})");

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    return TaskCache.FALSE;

                if (!data.Bank.TryGetValue(bankPack, out var cBank))
                    return TaskCache.FALSE;

                var cItem1 = GetItem(cBank, bankSlot1);
                var cItem2 = GetItem(cBank, bankSlot2);

                if (HasSameContents(cItem1, item2) && HasSameContents(cItem2, item1))
                {
                    source.TrySetResult(Expectation.Success);

                    return TaskCache.FALSE;
                }

                //two items that stack merge into b and empty a, unlike the inventory's imove
                if ((item1 != null)
                    && (item2 != null)
                    && (cItem1 == null)
                    && (cItem2 != null)
                    && cItem2.Name.EqualsI(item2.Name)
                    && (cItem2.Quantity == (item1.Quantity + item2.Quantity)))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "move",
                a = bankSlot1,
                b = bankSlot2,
                pack = bankPack
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();

        //a pack arrives trimmed to its highest occupied slot, so a valid slot past the array's end reads as empty
        static Item? GetItem(IReadOnlyList<Item?> pack, int slot) => (uint)slot < (uint)pack.Count ? pack[slot] : null;
    }

    /// <summary>
    ///     Asynchronously swaps the items between two inventory slots, or moves an item from one slot to another.
    /// </summary>
    /// <param name="inventorySlot1">A slot index within the inventory.</param>
    /// <param name="inventorySlot2">A slot index within the inventory.</param>
    /// <exception cref="ArgumentOutOfRangeException">inventorySlot1</exception>
    /// <exception cref="ArgumentOutOfRangeException">inventorySlot2</exception>
    public async Task SwapInventorySlotsAsync(int inventorySlot1, int inventorySlot2)
    {
        //imove takes any index below items.length, not just below isize, so it can reach a slot the bags overflowed into
        var addressable = Math.Max(Character.InventorySize, Character.Inventory.Count);

        if ((inventorySlot1 < 0) || (inventorySlot1 >= addressable))
            throw new ArgumentOutOfRangeException(nameof(inventorySlot1));

        if ((inventorySlot2 < 0) || (inventorySlot2 >= addressable))
            throw new ArgumentOutOfRangeException(nameof(inventorySlot2));

        var item1 = Character.Inventory[inventorySlot1];
        var item2 = Character.Inventory[inventorySlot2];

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                //a frame can carry a shorter inventory than the one these slots were read from
                // ReSharper disable once ConditionIsAlwaysTrueOrFalseAccordingToNullableAPIContract
                if ((data.Inventory == null) || (inventorySlot1 >= data.Inventory.Count) || (inventorySlot2 >= data.Inventory.Count))
                    return TaskCache.FALSE;

                var cItem1 = data.Inventory[inventorySlot1];
                var cItem2 = data.Inventory[inventorySlot2];

                if (HasSameContents(cItem1, item2) && HasSameContents(cItem2, item1))
                {
                    source.TrySetResult(Expectation.Success);

                    return TaskCache.FALSE;
                }

                //two items that stack merge into the first slot and empty the second
                if ((item1 != null)
                    && (item2 != null)
                    && (cItem2 == null)
                    && (cItem1 != null)
                    && cItem1.Name.EqualsI(item1.Name)
                    && (cItem1.Quantity == (item1.Quantity + item2.Quantity)))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.InventoryMove,
            new
            {
                a = inventorySlot1,
                b = inventorySlot2
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>
    ///     Asynchronously transports from the current map to given spawn in the given map.
    /// </summary>
    /// <param name="map">The map to transport to.</param>
    /// <param name="spawnIndex">The spawn index on the map to transport to.</param>
    /// <returns>
    ///     <see cref="NewMapData" />
    ///     <br />
    ///     Information about our location and map after we transport.
    /// </returns>
    public async Task TransportAsync(string map, int spawnIndex)
    {
        //ahead of the callbacks below, which would otherwise listen through whatever the hook emits
        await RaiseBeforeEscapeAsync(CancellationToken.None);

        var source = new TaskCompletionSource<Expectation<NewMapData>>(TaskCreationOptions.RunContinuationsAsynchronously);

        //a bank door's first answer: the emit is taken, and the map change follows once the bank has loaded
        var inProgress = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.TransportFailed    => source.TrySetResult("Transport failed. (can't walk, or jailed)"),
                    GameResponseType.CantEnter          => source.TrySetResult("Transport failed. (can't enter)"),
                    GameResponseType.CantEscape         => source.TrySetResult("Transport failed. (can't escape)"),
                    GameResponseType.TransportCantReach => source.TrySetResult("Transport failed. (can't reach)"),
                    GameResponseType.TransportCantItem  => source.TrySetResult($"Transport failed. ({DescribeMissingKey(data)})"),
                    GameResponseType.BankOperationInProgress => source.TrySetResult(
                        "Transport failed. (the previous bank door is still landing)"),
                    GameResponseType.BankOperation => source.TrySetResult($"Transport failed. (bank {data.Reason ?? "error"})"),
                    _ when data.InProgress && "transport".EqualsI(data.Place!) => inProgress.TrySetResult(),
                    _ when data.Failed && "transport".EqualsI(data.Place!) => source.TrySetResult(
                        $"Transport failed. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        using var newMapCallback = Socket.On<NewMapData>(
            ALSocketMessageType.NewMap,
            data =>
            {
                if (data.Map.EqualsI(map))
                    source.TrySetResult(data);

                return TaskCache.FALSE;
            });

        //read before the emit: past it the character is on the other side
        var fromBank = GameData.Maps[Character.Map]?.Mount ?? false;

        await Socket.EmitAsync(
            ALSocketEmitType.Transport,
            new
            {
                to = map,
                s = spawnIndex
            });

        NewMapData newMap = await DoorWait.WaitForLandingAsync(
            source.Task,
            inProgress.Task,
            ALClientSettings.NetworkTimeoutMS,
            ALClientSettings.BankCrossingTimeoutMS,
            pending => BankCrossingPending = pending);

        //if we're entering a bank, wait for bank data to populate
        var newData = GameData.Maps[newMap.Map];

        if (newData == null)
            return;

        //the emit hook priced the door; the mount or unmount the server bills beside it depends on both ends
        CallMeter.Charge(ALSocketEmitType.Transport, CallCost.CalculateBankCrossingCost(fromBank, newData.Mount));

        if (newMap.Map.ContainsI("bank") && newData.Mount)
            await WaitForBankAsync();
    }

    /// <summary>
    ///     Asynchronously enters a key-locked dungeon, either opening a new one or joining an existing one by id.
    /// </summary>
    /// <param name="place">
    ///     The dungeon's map name: crypt, winter_instance, spider_instance or tomb.
    /// </param>
    /// <param name="instance">
    ///     An existing instance's id to join, or null to open a new one. Joining consumes nothing; opening consumes that
    ///     dungeon's key.
    /// </param>
    /// <returns>
    ///     The instance id we landed in, read off the new map frame.
    /// </returns>
    /// <remarks>
    ///     Uses <c>enter</c>, not <c>transport</c>, which refuses a dungeon payload. Refused from further than 120 units of
    ///     the dungeon's fixed reference point.
    /// </remarks>
    /// <exception cref="ArgumentNullException">place</exception>
    /// <exception cref="DungeonEntryException">The server refused the entry.</exception>
    public async Task<string> EnterDungeonAsync(string place, string? instance = null)
    {
        ArgumentNullException.ThrowIfNull(place);

        //ahead of the callbacks below, which would otherwise listen through whatever the hook emits
        await RaiseBeforeEscapeAsync(CancellationToken.None);

        var source = new TaskCompletionSource<Expectation<NewMapData>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.TransportCantItem => source.TrySetResult(
                        new DungeonEntryException(data.ResponseType, $"Can't enter the dungeon. ({DescribeMissingKey(data)})")),
                    GameResponseType.TransportCantInvalid => source.TrySetResult(
                        new DungeonEntryException(data.ResponseType, "Can't enter the dungeon. (that instance is gone)")),
                    GameResponseType.TransportCantReach => source.TrySetResult(
                        new DungeonEntryException(data.ResponseType, "Can't enter the dungeon. (can't reach)")),
                    GameResponseType.TransportFailed => source.TrySetResult(
                        new DungeonEntryException(data.ResponseType, "Can't enter the dungeon. (can't walk, or jailed)")),
                    GameResponseType.CantEnter => source.TrySetResult(
                        new DungeonEntryException(data.ResponseType, "Can't enter the dungeon. (can't enter)")),
                    GameResponseType.CantEscape => source.TrySetResult(
                        new DungeonEntryException(data.ResponseType, "Can't enter the dungeon. (can't escape)")),
                    _ when data.Failed && "transport".EqualsI(data.Place!) => source.TrySetResult(
                        new DungeonEntryException(
                            data.ResponseType,
                            $"Can't enter the dungeon. ({data.Reason ?? data.ResponseType.ToString()})")),
                    _ => false
                };

                return Task.FromResult(result);
            });

        using var newMapCallback = Socket.On<NewMapData>(
            ALSocketMessageType.NewMap,
            data =>
            {
                if (data.Map.EqualsI(place))
                    source.TrySetResult(data);

                return TaskCache.FALSE;
            });

        //an absent name opens a new instance, while an empty one joins an instance called "" and is refused
        await Socket.EmitAsync(
            ALSocketEmitType.Enter,
            string.IsNullOrWhiteSpace(instance)
                ? new
                {
                    place
                }

                // ReSharper disable once RedundantCast
                : (object)new
                {
                    place,
                    name = instance
                });

        NewMapData newMap = await source.Task.WithNetworkTimeout();

        //in tells one copy of a dungeon from another, and can be missing; a join falls back to the name asked for
        var resolvedInstance = !string.IsNullOrWhiteSpace(newMap.In)
            ? newMap.In
            : !string.IsNullOrWhiteSpace(instance)
                ? instance
                : newMap.Map;

        //OnNewMapAsync already applied whatever in the frame carried, empty on a join; Character.In can be null
        if (!string.Equals(Character.In, resolvedInstance, StringComparison.OrdinalIgnoreCase))
            Character.UpdateMap(resolvedInstance, Character.Map);

        return resolvedInstance;
    }

    /// <summary>
    ///     Builds the reason for a <c>transport_cant_item</c> refusal, naming the items the door still needs when the server
    ///     sent them.
    /// </summary>
    /// <param name="data">The refusal.</param>
    /// <returns>
    ///     "no key", or "needs " and each needed item with its count.
    /// </returns>
    private static string DescribeMissingKey(GameResponseData data)
    {
        if (data.NeededItems is not { Count: > 0 } neededItems)
            return "no key";

        return "needs " + string.Join(", ", neededItems.Select(kvp => $"{kvp.Value} {kvp.Key}"));
    }

    /// <summary>Asynchronously unequips an item from a slot.</summary>
    /// <param name="slot">The slot of the item to unequip.</param>
    /// <returns>
    ///     <see cref="InventoryIndexer" />
    ///     <br />
    ///     Information about the item that was unequiped within the inventory.
    /// </returns>
    /// <exception cref="InvalidOperationException">
    ///     Failed to unequip item {itemNameOrSlot}. ({reason})
    /// </exception>
    public async Task<InventoryIndexer> UnequipAsync(Slot slot)
    {
        var item = Character.Slots[slot];

        if (item == null)
            throw new InvalidOperationException($"Failed to unequip item {slot}. (no item in slot)");

        if (Character.EmptySlots <= 0)
            throw new InvalidOperationException($"Failed to unequip item {item.Name}. (no space)");

        var source = new TaskCompletionSource<Expectation<InventoryIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);

        //indexes rather than items, since items compare by reference across frames
        var occupiedBefore = Character.Inventory
                                      .AsIndexed()
                                      .Select(indexed => indexed.Index)
                                      .ToHashSet();

        //every unequip refusal is a game_response with place "unequip"; a gear swap keeps an equip in flight beside it
        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                //the literal is the receiver, since Place can be null
                if (!data.Failed || !"unequip".EqualsI(data.Place!))
                    return TaskCache.FALSE;

                switch (data.ResponseType)
                {
                    case GameResponseType.Invalid:
                        source.TrySetResult($"Failed to unequip item {item.Name}. (no item in that slot)");

                        break;
                    case GameResponseType.NoSpace:
                        source.TrySetResult($"Failed to unequip item {item.Name}. (no space)");

                        break;
                }

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                var slotItem = data.Slots[slot];

                if (slotItem == null)
                {
                    //an equip in flight beside this can displace an identical item, so match by the slot that was empty
                    var inventoryItem = Character.Inventory.FindLandedItem(occupiedBefore, item.Name, item.Level);

                    if (inventoryItem != null)
                        source.TrySetResult(inventoryItem);
                }

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Unequip,
            new
            {
                slot
            });

        return await source.Task.WithNetworkTimeout();
    }

    /// <summary>Attempts to upgrade an item.</summary>
    /// <param name="inventorySlot">The inventory index of the item.</param>
    /// <param name="scrollIndex">The inventory index of the compound scroll.</param>
    /// <param name="offeringIndex">Optional: the inventory index of a tribute item.</param>
    /// <returns>
    ///     <see cref="bool" />
    ///     <br />
    ///     <c>true</c> if the upgrade succeeded, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="InvalidOperationException">Failed to upgrade. ({reason})</exception>
    public async Task<bool> UpgradeAsync(int inventorySlot, int scrollIndex, int? offeringIndex = null)
    {
        var item = Character.Inventory[inventorySlot];
        var source = new TaskCompletionSource<Expectation<bool?>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.UpgradeNoItem => source.TrySetResult("Failed to compound. (items not the same)"),
                    GameResponseType.UpgradeInProgress => source.TrySetResult("Failed to upgrade. (already upgrading)"),
                    GameResponseType.UpgradeIncompatibleScroll => source.TrySetResult("Failed to upgrade. (wrong scroll)"),
                    GameResponseType.UpgradeNoScroll => source.TrySetResult("Failed to upgrade. (no scroll)"),
                    GameResponseType.UpgradeMismatch => source.TrySetResult("Failed to upgrade. (unknown, this seems to be a catch-all)"),
                    GameResponseType.UpgradeCant => source.TrySetResult("Failed to upgrade. (item not upgradable)"),
                    GameResponseType.UpgradeInvalidOffering => source.TrySetResult("Failed to upgrade. (offering is not an offering)"),

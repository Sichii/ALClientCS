    /// <summary>
    ///     Asynchronously sends gold to a player.
    /// </summary>
    /// <param name="amount">
    ///     The amount of gold to send.
    /// </param>
    /// <param name="toPlayerId">
    ///     The id of the player to send gold to.
    /// </param>
    /// <param name="distanceCheck">
    ///     Whether or not to check distance.
    /// </param>
    /// <exception cref="ArgumentNullException">
    ///     toPlayerId
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to send {amount} gold to {toPlayerId}. ({reason})
    /// </exception>
    public async Task SendGoldAsync(long amount, string toPlayerId, bool distanceCheck = true)
    {
        if (string.IsNullOrEmpty(toPlayerId))
            throw new ArgumentNullException(nameof(toPlayerId));

        var shouldChange = (amount > 0) && Character.Gold.IsGreater(0, CORE_CONSTANTS.EPSILON);

        if (!shouldChange || (amount > (long)Character.Gold))
            throw new InvalidOperationException($"Failed to send {amount} gold to {toPlayerId}. (invalid amount)");

        if (distanceCheck)
        {
            if (!Players.TryGetValue(toPlayerId, out var player))
                throw new InvalidOperationException($"Failed to send {amount} gold to {toPlayerId}. (get closer)");

            if (Character.DistanceWithMapCheck(player) > CORE_CONSTANTS.TRADE_RANGE)
                throw new InvalidOperationException($"Failed to send {amount} gold to {toPlayerId}. (get closer)");
        }

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);
        var previousGold = Character.Gold;

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.Distance when "send".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to send {amount} gold to {toPlayerId}. (get closer)"),
                    _ when data.Failed && "send".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to send {amount} gold to {toPlayerId}. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                var didChange = !previousGold.IsNear(data.Gold, CORE_CONSTANTS.EPSILON);

                if (shouldChange && didChange && data.Gold.IsLess(previousGold, CORE_CONSTANTS.EPSILON))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Send,
            new
            {
                gold = amount,
                name = toPlayerId
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>
    ///     Asynchronously sends an item to a player.
    /// </summary>
    /// <param name="inventorySlot">
    ///     The slot of the item to send.
    /// </param>
    /// <param name="toPlayerId">
    ///     The id of the player to send to.
    /// </param>
    /// <param name="quantity">
    ///     The quantity of the item to send.
    /// </param>
    /// <param name="distanceCheck">
    ///     Whether or not to perform a distance check.
    /// </param>
    /// <exception cref="ArgumentNullException">
    ///     toPlayerId
    /// </exception>
    /// <exception cref="ArgumentOutOfRangeException">
    ///     quantity
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to send {quantity} of item {itemNameOrSlot} to {toPlayerId}. ({reason})
    /// </exception>
    public async Task SendItemAsync(
        int inventorySlot,
        string toPlayerId,
        int quantity = 1,
        bool distanceCheck = true)
    {
        if (string.IsNullOrEmpty(toPlayerId))
            throw new ArgumentNullException(nameof(toPlayerId));

        if (quantity <= 0)
            throw new ArgumentOutOfRangeException(nameof(quantity));

        var item = Character.Inventory[inventorySlot];

        if (item == null)
            throw new InvalidOperationException($"Failed to send {quantity} of item {inventorySlot} to {toPlayerId}. (no item)");

        if (item.Quantity < quantity)
            throw new InvalidOperationException($"Failed to send {quantity} of item {item.Name} to {toPlayerId}. (invalid quantity)");

        if (distanceCheck)
        {
            if (!Players.TryGetValue(toPlayerId, out var toPlayer))
                throw new InvalidOperationException($"Failed to send {quantity} of item {item.Name} to {toPlayerId}. (get closer)");

            if (Character.DistanceWithMapCheck(toPlayer) > CORE_CONSTANTS.TRADE_RANGE)
                throw new InvalidOperationException($"Failed to send {quantity} of item {item.Name} to {toPlayerId}. (get closer)");
        }

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.SendNoItem => source.TrySetResult(
                        $"Failed to send {quantity} of item {item.Name} to {toPlayerId}. (no item)"),
                    GameResponseType.SendNoSpace => source.TrySetResult(
                        $"Failed to send {quantity} of item {item.Name} to {toPlayerId}. (target no space)"),
                    GameResponseType.Distance when "send".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to send {quantity} of item {item.Name} to {toPlayerId}. (get closer)"),

                    //this is ok because it happens after we receive new player data.
                    //
                    //the quantity is the server's, not ours: it clamps the order to the stack it actually holds
                    //(min(item.q, requested)), so a stack that shrank between our read of it and its handler is
                    //acknowledged for less than we asked - a send that happened, not one that failed. Demanding
                    //equality left that acknowledgement unmatched and spent the full network timeout on a transfer
                    //the server had already made, which throws out of whatever was mid-delivery
                    GameResponseType.ItemSent when toPlayerId.EqualsI(data.Name!)
                                                   && (data.Item?.Name.EqualsI(item.Name) == true)
                                                   && (data.Quantity <= quantity) => source.TrySetResult(Expectation.Success),
                    _ when data.Failed && "send".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to send {quantity} of item {item.Name} to {toPlayerId}. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Send,
            new
            {
                name = toPlayerId,
                num = inventorySlot,
                q = quantity
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }


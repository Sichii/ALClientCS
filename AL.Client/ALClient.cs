                var result = data.ResponseType switch
                {
                    GameResponseType.BuySuccess => source.TrySetResult(
                        new SimpleIndexer
                        {
                            Index = data.SlotNum,
                            Item = new SimpleItem
                            {
                                Name = data.Name!,
                                Quantity = data.Quantity
                            }
                        }),
                    GameResponseType.BuyCantNPC   => source.TrySetResult($"Failed to buy {itemName}. (wrong npc)"),
                    GameResponseType.BuyCantSpace => source.TrySetResult($"Failed to buy {itemName}. (not enough space)"),
                    GameResponseType.BuyCost      => source.TrySetResult($"Failed to buy {itemName}. (not enough gold)"),
                    GameResponseType.Distance when "buy".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to buy {itemName}. (get closer)"),
                    _ when data.Failed && "buy".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to buy {itemName}. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        if (GameData.Items[itemName]?.StackSize > 1)
            await Socket.EmitAsync(
                ALSocketEmitType.Buy,
                new
                {
                    name = itemName,
                    quantity
                });
        else
            await Socket.EmitAsync(
                ALSocketEmitType.Buy,
                new
                {
                    name = itemName
                });

        return await source.Task.WithNetworkTimeout();
    }

    /// <summary>
    ///     Asynchronously attempts to buy an item from a player.
    /// </summary>
    /// <param name="playerName">
    ///     The name of the player to buy from.
    /// </param>
    /// <param name="slot">
    ///     The slot the item is in.
    /// </param>
    /// <param name="item">
    ///     The item to buy
    /// </param>
    /// <param name="quantity">
    ///     The quantity of the item to buy.
    /// </param>
    /// <returns>
    ///     <see cref="InventoryIndexer" />
    ///     <br />
    ///     Information about the item that was bought.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    ///     playerName
    /// </exception>
    /// <exception cref="ArgumentNullException">
    ///     item
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     {reason}
    /// </exception>
    public async Task<InventoryIndexer> BuyFromPlayerAsync(
        string playerName,
        TradeSlot slot,
        TradeItem item,
        int quantity = 1)
    {
        if (string.IsNullOrEmpty(playerName))
            throw new ArgumentNullException(nameof(playerName));

        ArgumentNullException.ThrowIfNull(item);

        // ReSharper disable once ConditionIsAlwaysTrueOrFalseAccordingToNullableAPIContract
        if (!Players.TryGetValue(playerName, out var player) || player is null)
            throw new InvalidOperationException($"Failed to buy {item.Name} from {playerName}. (seller gone)");

        if (Character.DistanceWithMapCheck(player) > CORE_CONSTANTS.NPC_RANGE)
            throw new InvalidOperationException($"Failed to buy {item.Name} from {playerName}. (get closer)");

        var slotItem = player.Slots[slot.ToSlot()];

        if ((slotItem == null) || (slotItem.Id != item.Id))
            throw new InvalidOperationException($"Failed to buy {item.Name} from {playerName}. (wrong id)");

        var source = new TaskCompletionSource<Expectation<InventoryIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);

        var inventorySnapshot = Character.Inventory.AsIndexed();
        var existingTotal = Character.Inventory.CountOf(item.Name);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = false;

                if ((data.ResponseType == GameResponseType.Distance) && "trade_buy".EqualsI(data.Place!))
                    result = source.TrySetResult($"Failed to buy {item.Name} from {playerName}. (get closer)");
                else if (data.Failed && "trade_buy".EqualsI(data.Place!))
                    result = source.TrySetResult(
                        $"Failed to buy {item.Name} from {playerName}. ({data.Reason ?? data.ResponseType.ToString()})");

                return Task.FromResult(result);
            });

        using var gameLogCallback = Socket.On<GameMessageData>(
            ALSocketMessageType.GameLog,
            data =>
            {
                var result = false;
                var message = data.Message;

                if (message.EqualsI("not enough gold") || message.EqualsI("you can't buy that many") || message.EqualsI("seller gone"))
                    result = source.TrySetResult($"Failed to buy {item.Name} from {playerName}. ({message})");

                return Task.FromResult(result);
            });

        using var disappearingTextCallback = Socket.On<DisappearingTextData>(
            ALSocketMessageType.DisappearingText,
            data =>
            {
                var result = false;

                if (data.Message.EqualsI("no space"))
                    result = source.TrySetResult($"Failed to buy {item.Name} from {playerName}. (no space)");

                return Task.FromResult(result);
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                var newTotal = data.Inventory.CountOf(item.Name);

                if ((newTotal - existingTotal) == quantity)
                    source.TrySetResult(
                        data.Inventory
                            .AsIndexed()
                            .Except(inventorySnapshot)
                            .First());

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.TradeBuy,
            new
            {
                slot,
                id = playerName,
                rid = item.Id,
                q = quantity.ToString()
            });

        return await source.Task.WithNetworkTimeout();
    }


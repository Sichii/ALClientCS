    #region Checks
    /// <summary>
    ///     Determines whether the open bank refuses an NPC trade, which the server answers with <c>cant_in_bank</c> before any
    ///     distance check, computer or not.
    /// </summary>
    /// <param name="distanceCheck">
    ///     The caller's distance flag; false asks what a stall would answer, which the bank does not refuse.
    /// </param>
    /// <returns>
    ///     <c>true</c> if the bank refuses the trade; otherwise, <c>false</c>.
    /// </returns>
    /// <remarks>
    ///     Reads <c>Character.Bank</c>, not <see cref="Bank" />, which stays populated after the first visit.
    /// </remarks>
    private bool IsRefusedInBank(bool distanceCheck) => distanceCheck && Character.Bank is not null;

    /// <summary>Determines if you should be able to buy an item.</summary>
    /// <param name="itemName">The name of the buyable item.</param>
    /// <param name="fromPonty">
    ///     Whether or not you're trying to buy it from Ponty.
    /// </param>
    /// <param name="distanceCheck">Whether or not to include a distance check.</param>
    /// <returns>
    ///     <see cref="bool" />
    ///     <br />
    ///     <c>true</c> if the item can be bought, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="ArgumentNullException">itemName</exception>
    public bool CanBuy(string itemName, bool fromPonty = false, bool distanceCheck = true)
    {
        if (string.IsNullOrEmpty(itemName))
            throw new ArgumentNullException(nameof(itemName));

        //not == 0: esize goes negative when the bag holds more than isize
        if (Character.EmptySlots <= 0)
            return false;

        var data = GameData.Items[itemName];

        if (data == null)
            return false;

        //"g" is the item's value; "gold" on an item is the gold-find stat and is 0 for almost everything
        var price = data.GoldValue;

        if (fromPonty)
            price *= data.Cash > 0 ? CONSTANTS.PONTY_CASH_MARKUP : CONSTANTS.PONTY_MARKUP;

        if (price > Character.Gold)
            return false;

        if (IsRefusedInBank(distanceCheck))
            return false;

        //ahead of the computer check: sbuy tests a hardcoded 500 against Ponty and has no computer waiver
        if (fromPonty)
            return !distanceCheck
                   || GameData.NPCs["secondhands"]!.Locations.Any(location
                       => location.DistanceWithMapCheck(Character) < CORE_CONSTANTS.NPC_RANGE);

        //the server refuses a name no NPC sells with buy_cant_npc before it checks distance
        if (data.ObtainType != ObtainType.Buy)
            return false;

        return !distanceCheck
               || HasComputer
               || data.ObtainableFromNPC!.Locations.Any(location => Character.DistanceWithMapCheck(location) < CORE_CONSTANTS.NPC_RANGE);
    }

    /// <summary>
    ///     Determines if you should be able to craft an item.
    /// </summary>
    /// <param name="itemName">The name of a craftable item.</param>
    /// <param name="includeBank">
    ///     Whether or not to include banked gold/items in the check. (only works if <see cref="Bank" /> has been populated)
    /// </param>
    /// <param name="distanceCheck">Whether or not to include a distance check.</param>
    /// <returns>
    ///     <see cref="bool" />
    ///     <br />
    ///     <c>true</c> if the item can be crafted, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="ArgumentNullException">itemName</exception>
    /// <remarks>
    ///     There should never be a reason to use <paramref name="includeBank" /> and <paramref name="distanceCheck" />
    ///     together.
    /// </remarks>
    public bool CanCraft(string itemName, bool includeBank = false, bool distanceCheck = true)
    {
        if (string.IsNullOrEmpty(itemName))
            throw new ArgumentNullException(nameof(itemName));

        var data = GameData.Items[itemName];

        if ((data?.ObtainType != ObtainType.Craft) || (data.ObtainableFromNPC == null))
            return false;

        var gold = Character.Gold;

        if (includeBank && (Bank != null))
            gold += Bank.Gold;

        if (data.Recipe!.Cost > gold)
            return false;

        foreach ((var quantity, var name, var level) in data.Recipe!.Items)
            if (Character.Inventory.FindItem(name, level, quantityMin: (int)quantity) == null)
                if (!includeBank || (Bank?.FindItem(name, level, quantityMin: (int)quantity) == null))
                    return false;

        return !IsRefusedInBank(distanceCheck)
               && (!distanceCheck
                   || HasComputer
                   || data.ObtainableFromNPC.Locations.Any(location
                       => location.DistanceWithMapCheck(Character) < CORE_CONSTANTS.NPC_RANGE));
    }

    /// <summary>
    ///     Determines if you should be able to exchange an item.
    /// </summary>
    /// <param name="itemName">The name of the exchangeable item.</param>
    /// <param name="distanceCheck">Whether or not to include a distance check.</param>
    /// <returns>
    ///     <see cref="bool" />
    ///     <br />
    ///     <c>true</c> if the item can be exchanged, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="ArgumentNullException">itemName</exception>
    public bool CanExchange(string itemName, bool distanceCheck = true)
    {
        if (string.IsNullOrEmpty(itemName))
            throw new ArgumentNullException(nameof(itemName));

        var data = GameData.Items[itemName];

        if ((data?.ExchangeCount == null) || (data.ExchangeAtNPC == null))
            return false;

        //one slot must hold the whole count; the server does not sum stacks
        if (Character.Inventory.FindItem(itemName, quantityMin: data.ExchangeCount.Value) == null)
            return false;

        return !IsRefusedInBank(distanceCheck)
               && (!distanceCheck
                   || HasComputer
                   || data.ExchangeAtNPC.Locations.Any(location => location.DistanceWithMapCheck(Character) < CORE_CONSTANTS.NPC_RANGE));
    }

    /// <summary>
    ///     Determines if you should be able to sell an item.
    /// </summary>
    /// <param name="itemName">The name of the sellable item.</param>
    /// <param name="distanceCheck">Whether or not to include a distance check.</param>
    /// <returns>
    ///     <c>true</c> if the item can be sold, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="ArgumentNullException">itemName</exception>
    public bool CanSell(string itemName, bool distanceCheck = true)
    {
        if (string.IsNullOrEmpty(itemName))
            throw new ArgumentNullException(nameof(itemName));

        if (!Character.Inventory.ContainsItem(itemName))
            return false;

        if (IsRefusedInBank(distanceCheck))
            return false;

        if (!distanceCheck || HasComputer)
            return true;

        var map = GameData.Maps[Character.Map];

        if (map == null)
            return true;

        foreach (var npc in map.NPCs)
            if ((npc.Data?.Items != null)
                && npc.Data.Locations.Any(location => location.DistanceWithMapCheck(Character) < CORE_CONSTANTS.NPC_RANGE))
                return true;

        return false;
    }

    /// <summary>Determines if this skill can be used.</summary>
    /// <param name="skillName">The name of the skill.</param>
    /// <param name="checkWeapon">
    ///     Whether or not to check the equipped weapon against the required weapon type. (if there is one)
    /// </param>
    /// <param name="checkSlotItems">
    ///     Whether or not to check that one of the items the skill names is worn in its slot. (if it names any) False for a
    ///     caller about to equip one for the cast, like <paramref name="checkWeapon" />.
    /// </param>
    /// <returns>
    ///     <c>true</c> if the skill can be used, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="ArgumentNullException">skillName</exception>
    public bool CanUseSkill(string skillName, bool checkWeapon = true, bool checkSlotItems = true)
    {
        if (string.IsNullOrEmpty(skillName))
            throw new ArgumentNullException(nameof(skillName));

        //the server's is_disabled, which refuses every skill with "disabled"
        if (Character.RIP
            || Character.Conditions.ContainsKey(Condition.Stunned)
            || Character.Conditions.ContainsKey(Condition.Fingered)
            || Character.Conditions.ContainsKey(Condition.Stoned)
            || Character.Conditions.ContainsKey(Condition.Deepfreezed)
            || Character.Conditions.ContainsKey(Condition.Sleeping)
            || (skillName.EqualsI("blink") && Character.Conditions.ContainsKey(Condition.Dampened))
            || !IsOffCooldown(skillName))
            return false;

        var data = GameData.Skills[skillName]!;

        if ((data.Classes != null) && !data.Classes.Contains(Character.Class))
            return false;

        if (data.Level.HasValue && (Character.Level < data.Level))
            return false;

        if (data.AttributeRequirements != null)
            foreach ((var attribute, var requiredValue) in data.AttributeRequirements)
            {
                var value = Character.Attributes.GetValueOrDefault(attribute, 0);

                if (requiredValue > value)
                    return false;
            }

        bool isAttack;

        if ((isAttack = skillName.EqualsI("attack")) || skillName.EqualsI("heal"))
        {
            if (Character.MP < Character.MPCost)
                return false;

            var mainHand = Character.Slots[Slot.MainHand];
            var mainHandData = mainHand?.GetData();
            var classData = Character.GetData();

            if ((mainHand == null)
                || (classData == null)
                || (mainHandData == null)
                || (!classData.CanMainHand(mainHandData.WeaponType) && !classData.Can2Hand(mainHandData.WeaponType)))
                return false;

            if (isAttack && mainHand.Name.EqualsI("dartgun") && (Character.Gold < 100))
                return false;
        } else if (Character.MP < data.MP)
            return false;

        if (!string.IsNullOrEmpty(data.Consume) && !Character.Inventory.ContainsItem(data.Consume))
            return false;

        if ((data.RequiredInventoryItems != null)
            && !data.RequiredInventoryItems.All(itemName => Character.Inventory.ContainsItem(itemName)))
            return false;

        if (checkSlotItems && (data.RequiredSlotItems != null))
        {
            var equipped = false;

            foreach ((var equipmentSlot, var itemName) in data.RequiredSlotItems)
            {
                var slotItem = Character.Slots[equipmentSlot.ToSlot()];

                if ((slotItem != null) && slotItem.Name.EqualsI(itemName))
                {
                    equipped = true;

                    break;
                }
            }

            if (!equipped)
                return false;
        }

        if (checkWeapon && (data.WeaponTypes != null))
        {
            var slotItem = Character.Slots[Slot.MainHand];

            if ((slotItem == null)
                || !data.WeaponTypes.Contains(
                    slotItem.GetData()
                            ?.WeaponType
                    ?? WeaponType.None))
                return false;
        }

        //shield slam is the one skill that asks about the offhand rather than the mainhand
        if (checkWeapon && data.OffhandType is { } offhandType)
        {
            var offhand = Character.Slots.GetValueOrDefault(Slot.OffHand);

            if ((offhand == null)
                || (offhand.GetData()
                           ?.Type
                    != offhandType))
                return false;
        }

        return true;
    }

    /// <summary>
    ///     Determines if this skill is off cooldown. (shared cooldown if it has one)
    /// </summary>
    /// <param name="skillName">The name of the skill.</param>
    /// <returns>
    ///     <c>true</c> if the skill is off cooldown, otherwise <c>false</c> .
    /// </returns>
    /// <exception cref="ArgumentNullException">skillName</exception>
    public bool IsOffCooldown(string skillName)
    {
        if (string.IsNullOrEmpty(skillName))
            throw new ArgumentNullException(nameof(skillName));

        var data = GameData.Skills[skillName];

        if (data == null)
            return false;

        var cooldownKey = data.GetCooldownKey(skillName);

        return !Cooldowns.TryGetValue(cooldownKey, out var cooldown) || cooldown.CanUse();
    }


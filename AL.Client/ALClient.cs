    /// <summary>
    ///     Asynchronously crafts an item.
    /// </summary>
    /// <param name="itemName">
    ///     The name of the item to craft.
    /// </param>
    /// <returns>
    ///     <see cref="InventoryIndexer" />
    ///     <br />
    ///     Information about the item that was crafted, and it's position in the inventory.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    ///     itemName
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to craft {itemName}. ({reason})
    /// </exception>
    public Task<InventoryIndexer> CraftAsync(string itemName)
    {
        if (string.IsNullOrEmpty(itemName))
            throw new ArgumentNullException(nameof(itemName));

        var recipe = GameData.Craft[itemName];

        if (recipe == null)
            throw new InvalidOperationException($"Failed to craft {itemName}. (not craftable)");

        var slots = new List<int>();

        foreach ((var quantity, var name, var level) in recipe.Items)
        {
            //exact stack preferred, over-sized one as fallback: the server only consults can_add_item when no
            //submitted slot is exact (node/server.js:6021-6031), so an exact match keeps space true and a full
            //inventory craftable - falling back to quantityMin is what makes an over-sized stack legal at all,
            //since the server's own rule is at-least rather than exact
            var result = Character.Inventory.FindItem(name, level, (int?)quantity)
                         ?? Character.Inventory.FindItem(name, level, quantityMin: (int)quantity);

            if (result == null)
                throw new InvalidOperationException($"Failed to craft {itemName}. (missing component)");

            slots.Add(result.Index);
        }

        return CraftAsync(itemName, slots);
    }

    /// <summary>
    ///     Asynchronously crafts an item out of slots the caller chose.
    /// </summary>
    /// <param name="itemName">
    ///     The name of the item to craft.
    /// </param>
    /// <param name="inventorySlots">
    ///     One inventory slot per recipe input, in the recipe's own order.
    /// </param>
    /// <remarks>
    ///     For a caller that keeps part of its inventory out of play. The overload above scans from index 0 and
    ///     prefers a slot holding exactly the recipe amount - which for a non-stackable input is every slot holding
    ///     one - so it will consume a low-indexed copy in preference to a higher-indexed over-sized one, and nothing
    ///     on this side knows which slots a caller considers off limits. Choosing the slots is the only way to say so
    ///     without restating the exact-before-over-sized preference, which exists to keep the server's <c>space</c>
    ///     flag true and is not the caller's to re-derive.
    /// </remarks>
    /// <returns>
    ///     <see cref="InventoryIndexer" />
    ///     <br />
    ///     Information about the item that was crafted, and it's position in the inventory.
    /// </returns>
    /// <exception cref="ArgumentNullException">
    ///     itemName
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to craft {itemName}. ({reason})
    /// </exception>
    public async Task<InventoryIndexer> CraftAsync(string itemName, IReadOnlyList<int> inventorySlots)
    {
        if (string.IsNullOrEmpty(itemName))
            throw new ArgumentNullException(nameof(itemName));

        var recipe = GameData.Craft[itemName];

        if (recipe == null)
            throw new InvalidOperationException($"Failed to craft {itemName}. (not craftable)");

        //the emit is a grid of (position, slot) pairs one per input, so a short or long list is a malformed craft
        //rather than one the server can refuse intelligibly
        if (inventorySlots.Count != recipe.Items.Count)
            throw new InvalidOperationException(
                $"Failed to craft {itemName}. (expected {recipe.Items.Count} slots, got {inventorySlots.Count})");

        if (recipe.Cost > Character.Gold)
            throw new InvalidOperationException($"Failed to craft {itemName}. (not enough gold)");

        var source = new TaskCompletionSource<Expectation<InventoryIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);
        var previousInventory = Character.Inventory.AsIndexed();

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.NoItem        => source.TrySetResult($"Failed to craft {itemName}. (missing component)"),
                    GameResponseType.GoldNotEnough => source.TrySetResult($"Failed to craft {itemName}. (not enough gold"),
                    _ when data.Failed && "craft".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to craft {itemName}. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                var craftedItem = data.Inventory
                                      .AsIndexed()
                                      .Except(previousInventory)
                                      .FirstOrDefault(indexed => indexed.Item.Name.EqualsI(itemName));

                if (craftedItem != null)
                    source.TrySetResult(craftedItem);

                return TaskCache.FALSE;
            });

        //the server reads x[1] as the inventory slot and x[0] as the position in the craft grid,
        //and it reads them off an "items" property rather than a bare array
        await Socket.EmitAsync(
            ALSocketEmitType.Craft,
            new
            {
                items = inventorySlots.Select((inventorySlot, gridPosition) => new[]
                {
                    gridPosition,
                    inventorySlot
                })
            });

        return await source.Task.WithNetworkTimeout();
    }

    /// <summary>
    ///     Asynchronously deposits gold in the bank.
    /// </summary>
    /// <param name="amount">
    ///     The amount of gold to deposit.
    /// </param>
    /// <returns>
    ///     <see cref="int" />
    ///     <br />
    ///     The amount of gold the character has after depositing.
    /// </returns>
    public async Task DepositGoldAsync(long amount)
    {
        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to deposit {amount} gold. (not in bank)");

        var shouldChange = (amount > 0) && Character.Gold.IsGreater(0, CORE_CONSTANTS.EPSILON);

        if (!shouldChange || (amount > (long)Character.Gold))
            throw new InvalidOperationException($"Failed to deposit {amount} gold. (invalid amount)");

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        var previousGold = Character.Gold;

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    source.TrySetResult($"Failed to deposit {amount} gold. (not in bank)");

                var didChange = !previousGold.IsNear(data.Gold, CORE_CONSTANTS.EPSILON);

                if (didChange)
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                amount,
                operation = "deposit"
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>
    ///     Asynchronously deposits an item in the bank.
    /// </summary>
    /// <param name="inventorySlot">
    ///     The slot in the inventory the item is currently at.
    /// </param>
    /// <param name="bankPack">
    ///     If specified, will try to find a slot in this bankPack to deposit the item.
    /// </param>
    /// <param name="bankSlot">
    ///     If specified with bankPack, will deposit the item in this bankPack, in this bankSlot if it is empty.
    /// </param>
    /// <returns>
    ///     <see cref="BankIndexer" />
    ///     <br />
    ///     Information about the item and it's index in the bank.
    /// </returns>
    /// <exception cref="ArgumentException">
    ///     If specifying bankSlot), must also specify bankPack.
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to deposit item {item}. ({reason})
    /// </exception>
    public async Task<BankIndexer> DepositItemAsync(int inventorySlot, BankPack? bankPack = null, int? bankSlot = null)
    {
        if ((bankSlot != null) && (bankPack == null))
            throw new ArgumentException($"If specifying {nameof(bankSlot)}, must also specify {nameof(bankPack)}.");

        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to deposit item {inventorySlot}. (not in bank)");

        var item = Character.Inventory[inventorySlot];

        if (item == null)
            throw new InvalidOperationException($"Failed to deposit item. (no item in slot {inventorySlot})");

        var indexedItem = new InventoryIndexer
        {
            Index = inventorySlot,
            Item = item
        };
        var optimalIndexes = FindOptimalBankIndex(indexedItem, bankPack, bankSlot);

        if (optimalIndexes == null)
            throw new InvalidOperationException($"Failed to deposit item {item.Name}. (no space)");

        (bankPack, bankSlot) = optimalIndexes.Value;
        var source = new TaskCompletionSource<Expectation<BankIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if (data.ResponseType == GameResponseType.Invalid)
                    source.TrySetResult($"Failed to deposit item {item.Name}. (invalid)");

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    source.TrySetResult($"Failed to deposit item {item.Name}. (not in bank)");
                else if ((data.Inventory[inventorySlot] == null) && data.Bank.TryGetValue(bankPack.Value, out var bankedItems))
                {
                    var probableIndex = bankedItems.FindIndex(b
                        => (b != null) && b.Name.EqualsI(item.Name) && (b.Level == item.Level) && (b.Quantity >= item.Quantity));

                    if (probableIndex == -1)
                        return TaskCache.FALSE;

                    var bankedItem = bankedItems[probableIndex]!;

                    source.TrySetResult(
                        new BankIndexer
                        {
                            BankPack = bankPack.Value,
                            Index = probableIndex,
                            Item = bankedItem
                        });
                }

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "swap",
                inv = inventorySlot,
                str = bankSlot.Value,
                pack = bankPack.Value
                               .ToString()
                               .ToLower()
            });

        return await source.Task.WithNetworkTimeout();
    }


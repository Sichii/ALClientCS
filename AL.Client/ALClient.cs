    /// <summary>
    ///     Subscribes, emits, and awaits the first matching message. <paramref name="handled" /> stops the message chain at
    ///     this subscriber, which only a request that owns its message type may do.
    /// </summary>
    private async Task<Expectation<T>> RequestAsync<T>(
        ALSocketMessageType messageType,
        ALSocketEmitType emitType,
        object? emitData = null,
        bool handled = true,
        int? timeoutMS = null,
        [CallerMemberName] string? caller = null)
    {
        var source = new TaskCompletionSource<Expectation<T>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var callback = Socket.On<T>(
            messageType,
            data =>
            {
                var result = source.TrySetResult(new Expectation<T>(data));

                return handled ? Task.FromResult(result) : TaskCache.FALSE;
            });

        if (emitData == null)
            await Socket.EmitAsync(emitType);
        else
            await Socket.EmitAsync(emitType, emitData);

        return timeoutMS.HasValue ? await source.Task.WithTimeout(timeoutMS.Value) : await source.Task.WithNetworkTimeout(caller);
    }

    /// <summary>
    ///     Consumes a potion or regen. The server acknowledges it with an eval carrying the shared pot cooldown, and
    ///     refuses it with a failed game_response. <paramref name="description" /> names the item in that failure.
    /// </summary>
    private async Task ConsumeAsync(
        ALSocketEmitType emitType,
        object emitData,
        string description,
        [CallerMemberName] string? caller = null)
    {
        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        //the refusal arm, and it has to be this event: the shared potion cooldown answers
        //`fail_response("not_ready", {ms})` (node/server.js:7202), which is a game_response and nothing else. This
        //used to watch for a "not ready" disappearing text, a string the server does not contain - so the single
        //most common outcome of all, using a potion a moment early, matched no expectation at all and spent the
        //whole network timeout before throwing one that named the wrong problem
        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if (!data.Failed)
                    return TaskCache.FALSE;

                switch (data.ResponseType)
                {
                    case GameResponseType.NotReady:
                        source.TrySetResult($"Failed to use {description}. (not ready for another {data.CooldownMS ?? 0:N0}ms)");

                        break;
                    case GameResponseType.ItemLocked:
                        source.TrySetResult($"Failed to use {description}. (item is locked)");

                        break;
                }

                return TaskCache.FALSE;
            });

        using var evalCallback = Socket.On<EvalData>(
            ALSocketMessageType.Eval,
            data =>
            {
                if (!string.IsNullOrEmpty(data.Code) && RegexCache.POT_TIMEOUT.IsMatch(data.Code))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(emitType, emitData);

        var expectation = await source.Task.WithNetworkTimeout(caller);
        expectation.ThrowIfUnsuccessful();
    }

    protected bool DestroyEntity(string id)
    {
        var result = Monsters.Remove(id, out _) || Players.Remove(id, out _);

        var bossInfoDic = (Dictionary<string, BossInfo>)EventsAndBosses.BossInfo;
        bossInfoDic.Remove(id);

        return result;
    }

    protected EntityBase? GetEntity(string id) => Players.GetValueOrDefault(id) as EntityBase ?? Monsters.GetValueOrDefault(id);

    /// <summary>
    ///     Finds a bank slot for the given inventory item: validates an explicit pack/slot pair, otherwise prefers stacking
    ///     onto an existing partial stack, else the first empty slot in an accessible pack on the current bank map. Requires
    ///     being in the bank (
    ///     <see cref="Bank" />
    ///     populated).
    /// </summary>
    public (BankPack BankPack, int BankSlot)? FindOptimalBankIndex(
        IIndexer<IInventoryItem> indexedInventoryItem,
        BankPack? bankPack = null,
        int? bankSlot = null)
    {
        //if both indexes are specified, just check that they are valid.
        if (bankPack.HasValue && bankSlot.HasValue)
            if (!Bank!.TryGetValue(bankPack.Value, out var bankedItems)
                || ((bankSlot.Value < bankedItems.Count) && (bankedItems[bankSlot.Value] != null)))
                return null;
            else
                return (bankPack.Value, bankSlot.Value);

        var item = indexedInventoryItem.Item;
        var itemData = item.GetData();
        var stackSize = itemData?.StackSize ?? 1;

        //an enumerable of acceptable bankpacks or the bankPack the user wants to use
        var availableBanks = bankPack.HasValue ? [bankPack.Value] : GetAvailableBankPacks();
        (BankPack, int)? firstEmptySlot = null;

        foreach (var bankPackIndex in availableBanks)
        {
            //check if they have access to the bankPack
            if (!Bank!.TryGetValue(bankPackIndex, out var bankItems))
                continue;

            //every slot of the pack, not every entry of the array the server sent. bank_add_item pushes
            //(node/server.js:2018) and pads nothing, so a pack arrives trimmed to its highest occupied slot and a
            //freshly bought one arrives as []. The server counts all 42 either way (js/old_common_functions.js:412),
            //so anything past the array's end is a free slot rather than no slot
            for (var itemSlotIndex = 0; itemSlotIndex < BANK_PACK_SIZE; itemSlotIndex++)
            {
                var bankedItem = itemSlotIndex < bankItems.Count ? bankItems[itemSlotIndex] : null;

                //if the slot is empty
                if (bankedItem == null)
                {
                    //if this item is not stackable, this is the first empty slot to place the item in so just break
                    //if this item IS stackable, continue looking for a slot we can stack the item into
                    if (stackSize == 1)
                        return (bankPackIndex, itemSlotIndex);

                    //if this is the first empty slot we've come across, save it for later
                    //if the item is stackable and we arent able to find a stackable index we will use this
                    firstEmptySlot ??= (bankPackIndex, itemSlotIndex);
                }

                //check if the item can stack onto this banked item
                else if ((stackSize > 1) && item.Name.EqualsI(bankedItem.Name) && ((item.Quantity + bankedItem.Quantity) <= stackSize))

                    //-1 allows the item to automatically stack
                    return (bankPackIndex, -1);
            }
        }

        return firstEmptySlot;
    }

    /// <summary>
    ///     Serializes game data, initializes caches and pathfinding
    /// </summary>
    /// <param name="unlockedDoors">
    /// </param>
    public static async Task InitializeAsync(IEnumerable<ILocation>? unlockedDoors = null)
    {
        var tasks = new List<Task>
        {
            Task.Run(() => RuntimeHelpers.RunClassConstructor(typeof(RegexCache).TypeHandle)),
            Task.Run(() => RuntimeHelpers.RunClassConstructor(typeof(TaskCache).TypeHandle)),
            Task.Run(async () =>
            {
                var jData = await AlApiClient.GetGameDataAsync();
                GameData.Populate(jData);
            })
        };

        await Task.WhenAll(tasks);

        if (unlockedDoors != null)
            foreach (var doorLoc in unlockedDoors)
            {
                var gMap = GameData.Maps[doorLoc.Map];
                var door = gMap!.Doors.FirstOrDefault(d => IPoint.Comparer.Equals(d, doorLoc));

                door?.Unlock();
            }

        Pathfinder.Initialize();
    }

    protected void SetCooldown(string skillName, float? cooldownMs = null)
    {
        var cooldownMultiplier = 1f;

        var data = GameData.Skills[skillName];

        if (data == null)
            return;

        if (!string.IsNullOrEmpty(data.SharedCooldown))
        {
            skillName = data.SharedCooldown;
            cooldownMultiplier = data.CooldownMultiplier ?? 1f;
            data = GameData.Skills[skillName]!;
        }

        if ((data.CooldownMS > 0) || skillName.EqualsI("attack"))
        {
            if (skillName.EqualsI("attack"))
                cooldownMs ??= 1000f / Character.Frequency;
            else
                cooldownMs ??= data.CooldownMS;

            var cooldownInfo = new CooldownInfo(cooldownMs.Value * cooldownMultiplier);
            cooldownInfo.CompensateOnce(PingManager.LowPercentileOffset);

            Cooldowns.AddOrUpdate(skillName, cooldownInfo, (_, _) => cooldownInfo);
        }
    }

    protected void UpdateMonsters(
        IReadOnlyList<Monster> monsters,
        string @in,
        string map,
        EntitiesUpdateType updateType)
    {
        if (updateType == EntitiesUpdateType.All)
            Monsters.Clear();

        foreach (var monster in monsters)
        {
            monster.UpdateMap(@in, map);
            monster.CompensateOnce(PingManager.LowPercentileOffset);

            if (Monsters.TryGetValue(monster.Id, out var existingMonster))
                existingMonster.Update(monster);
            else
            {
                //a freshly-sighted monster carries only the soft properties that differ from its def; fill the rest
                monster.BackfillSoftDefaults();

                var monsterData = monster.GetData();

                monster.SetBoundingBase(monsterData.BoundingBase);
                monster.SetHitBox(monsterData.HitBox);
                Monsters.TryAdd(monster.Id, monster);
            }
        }
    }

    protected void UpdatePlayers(
        IReadOnlyCollection<Player> players,
        string @in,
        string map,
        EntitiesUpdateType updateType)
    {
        if (updateType == EntitiesUpdateType.All)
            Players.Clear();

        foreach (var player in players)
        {
            player.UpdateMap(@in, map);
            player.CompensateOnce(PingManager.LowPercentileOffset);

            if (player.Equals(Character))
                Character.UpdateLocation(player);
            else if (Players.TryGetValue(player.Id, out var existing))
                existing.Update(player);
            else
            {
                player.SetBoundingBase(PATHFINDING_CONSTANTS.DEFAULT_BOUNDING_BASE);
                player.SetHitBox(GameData.DEFAULT_CHARACTER_HIT_BOX);
                Players.TryAdd(player.Id, player);
            }
        }
    }

    protected IEnumerable<BankPack> GetAvailableBankPacks()
    {
        if (string.IsNullOrEmpty(Character.Map))
            throw new ArgumentNullException(nameof(Character.Map));

        //bank_packs (js/old_common_functions.js:54) puts items0-7 on "bank", items8-23 on "bank_b" and items24-47
        //on "bank_u". BankPack.None occupies 0, so each pack's enum value is its number plus one
        return (Character.Map switch
        {
            "bank"   => Enumerable.Range(1, 8),
            "bank_b" => Enumerable.Range(9, 16),
            "bank_u" => Enumerable.Range(25, 24),
            _        => throw new InvalidOperationException("Not in a bank")
        }).Select(index => (BankPack)index);
    }

    /// <summary>
    ///     Completes when bank data is populated after entering a bank map. Times out with the network timeout if the bank
    ///     frame never arrives.
    /// </summary>
    public async Task WaitForBankAsync()
    {
        //check if bank is already populated
        if (Bank != null)
            return;

        //if not, set up a callback to expect bank data
        var source = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if ((data.Bank != null) || (Bank != null))
                    source.TrySetResult();

                return TaskCache.FALSE;
            });

        //check for bank data again (it could have been set while executing the previous statement
        if (Bank != null)
            return;

        //wait for it to be populated
        await source.Task.WithNetworkTimeout();
    }


    /// <summary>
    ///     Asynchronously attempts to exchange an item.
    /// </summary>
    /// <param name="inventorySlot">
    ///     The index of the item to exchange.
    /// </param>
    /// <returns>
    ///     <see cref="InventoryIndexer" />
    ///     <br />
    ///     The item received from the exchange.
    /// </returns>
    /// <exception cref="InvalidOperationException">
    /// </exception>
    public async Task<InventoryIndexer> ExchangeAsync(int inventorySlot)
    {
        if (inventorySlot >= Character.InventorySize)
            throw new InvalidOperationException("Failed to exchange. (index out of range)");

        var item = Character.Inventory[inventorySlot];

        if (item == null)
            throw new InvalidOperationException("Failed to exchange. (no item at index)");

        var itemData = item.GetData();

        if (itemData == null)
            throw new InvalidOperationException("Failed to exchange. (no data, contact me)");

        //exchangeability is the count alone, and asking for ExchangeAtNPC beside it refused 31 of the committed game data's 38
        //exchangeables outright: it was enriched only from an npc's token or the item's own quest, so gems,
        //boxes and every envelope carry none. Where an item is exchanged is a distance question the server settles
        //itself against the quest npc or the fixed exchange placement (node/server.js:6072-6077), not an existence one
        if (!itemData.ExchangeCount.HasValue)
            throw new InvalidOperationException("Failed to exchange. (item not exchangeable)");

        if (itemData.ExchangeCount > item.Quantity)
            throw new InvalidOperationException($"Failed to exchange. (you do not have {itemData.ExchangeCount})");

        var source = new TaskCompletionSource<Expectation<InventoryIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.ExchangeNotEnough => source.TrySetResult(
                        $"Failed to exchange. (youd to not have {itemData.ExchangeCount})"),
                    GameResponseType.Distance when "exchange".EqualsI(data.Place!) => source.TrySetResult(
                        "Failed to exchange. (get closer)"),
                    GameResponseType.ExchangeExisting => source.TrySetResult("Failed to exchange. (already exchanging)"),
                    GameResponseType.CantInBank       => source.TrySetResult("Failed to exchange. (can't exchange from bank)"),
                    _ when data.Failed && "exchange".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to exchange. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        var exchangeStarted = false;
        Inventory? itemsSnapshot = null;

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (!exchangeStarted
                    && (data.QueuedActions?.Exchange != null)
                    && data.QueuedActions.Exchange.CurrentMS.IsNear(data.QueuedActions.Exchange.LengthMS, CORE_CONSTANTS.EPSILON))
                    exchangeStarted = true;

                if (exchangeStarted)
                {
                    if (data.QueuedActions?.Exchange == null)
                        source.TrySetResult(
                            Character.Inventory
                                     .AsIndexed()
                                     .Except(itemsSnapshot!.AsIndexed())
                                     .First());
                    else
                        itemsSnapshot = Character.Inventory;
                }

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Exchange,
            new
            {
                item_num = inventorySlot,
                q = itemData.ExchangeCount
            });

        return await source.Task.WithTimeout(60000);
    }


    /// <summary>
    ///     Asynchronously unlocks a paid bank pack with gold, standing on the pack's floor map. Shells and key items are not
    ///     supported.
    /// </summary>
    /// <param name="pack">
    ///     The bank pack to unlock, e.g. <see cref="BankPack.Items3" />.
    /// </param>
    /// <exception cref="ArgumentOutOfRangeException">pack</exception>
    /// <exception cref="InvalidOperationException">Failed to unlock bank pack {pack}. ({reason})</exception>
    public async Task UnlockBankPackAsync(BankPack pack)
    {
        var packWire = pack.ToString()
                           .ToLowerInvariant();

        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to unlock bank pack {packWire}. (not in bank)");

        //bank_packs puts items0-7 on "bank", items8-23 on "bank_b" and items24-47 on "bank_u"
        var requiredMap = (int)pack switch
        {
            >= 1 and <= 8   => "bank",
            >= 9 and <= 24  => "bank_b",
            >= 25 and <= 48 => "bank_u",
            _               => throw new ArgumentOutOfRangeException(nameof(pack))
        };

        if (!Character.Map.EqualsI(requiredMap))
            throw new InvalidOperationException($"Failed to unlock bank pack {packWire}. (wrong bank)");

        //Character.Bank is the live frame; ALClient.Bank is the sticky cache and can lag a concurrent unlock
        if (Character.Bank.ContainsKey(pack))
            throw new InvalidOperationException($"Failed to unlock bank pack {packWire}. (already unlocked)");

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if ((data.ResponseType == GameResponseType.BankNewPack) && (string.IsNullOrEmpty(data.Pack) || packWire.EqualsI(data.Pack)))
                {
                    source.TrySetResult(Expectation.Success);

                    return TaskCache.FALSE;
                }

                if (data.Failed && "bank".EqualsI(data.Place!))
                    source.TrySetResult($"Failed to unlock bank pack {packWire}. ({data.ResponseType})");

                if (data.ResponseType == GameResponseType.GoldNotEnough)
                    source.TrySetResult($"Failed to unlock bank pack {packWire}. (not enough gold)");

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank?.ContainsKey(pack) == true)
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "unlock",
                pack = packWire,
                gold = 1
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>Asynchronously deposits an item in the bank.</summary>
    /// <param name="inventorySlot">
    ///     The slot in the inventory the item is currently at.
    /// </param>
    /// <param name="bankPack">
    ///     If specified, will try to find a slot in this bankPack to deposit the item.
    /// </param>
    /// <param name="bankSlot">
    ///     If specified with bankPack, will deposit the item into that exact slot, swapping with whatever is already there.
    ///     Pass <c>-1</c> to let the server pick, which is also how an item folds into a stack the pack already holds.
    /// </param>
    /// <returns>
    ///     <see cref="BankIndexer" />
    ///     <br />
    ///     Information about the item and it's index in the bank.
    /// </returns>
    /// <remarks>
    ///     Naming an occupied slot is a swap: the server writes the displaced item back into <paramref name="inventorySlot" />
    ///     , and the returned indexer describes only the deposited half.
    /// </remarks>
    /// <exception cref="ArgumentException">
    ///     If specifying bankSlot), must also specify bankPack.
    /// </exception>
    /// <exception cref="InvalidOperationException">Failed to deposit item {item}. ({reason})</exception>
    public async Task<BankIndexer> DepositItemAsync(int inventorySlot, BankPack? bankPack = null, int? bankSlot = null)
    {
        if ((bankSlot != null) && (bankPack == null))
            throw new ArgumentException($"If specifying {nameof(bankSlot)}, must also specify {nameof(bankPack)}.");

        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to deposit item {inventorySlot}. (not in bank)");

        //the bank handler clamps inv to isize-1 rather than refusing it, so an overflow slot is moved into the bags first
        if (inventorySlot >= Character.InventorySize)
        {
            var freeSlot = Enumerable.Range(0, Math.Min(Character.InventorySize, Character.Inventory.Count))
                                     .FirstOrDefault(slot => Character.Inventory[slot] is null, -1);

            if (freeSlot < 0)
                throw new InvalidOperationException(
                    $"Failed to deposit item {inventorySlot}. (overflow slot, and no free bag slot to move it into)");

            await SwapInventorySlotsAsync(inventorySlot, freeSlot);
            inventorySlot = freeSlot;
        }

        var item = Character.Inventory[inventorySlot];

        if (item == null)
            throw new InvalidOperationException($"Failed to deposit item. (no item in slot {inventorySlot})");

        var indexedItem = new InventoryIndexer
        {
            Index = inventorySlot,
            Item = item
        };

        //the caller's own intent, not whether FindOptimalBankIndex returned an occupied slot
        var namedSlot = bankSlot is >= 0;

        var optimalIndexes = FindOptimalBankIndex(indexedItem, bankPack, bankSlot);

        if (optimalIndexes == null)
            throw new InvalidOperationException($"Failed to deposit item {item.Name}. (no space)");

        (bankPack, bankSlot) = optimalIndexes.Value;

        Item? occupant = null;

        if (namedSlot && Bank!.TryGetValue(bankPack.Value, out var occupying) && (bankSlot.Value < occupying.Count))
            occupant = occupying[bankSlot.Value];

        var source = new TaskCompletionSource<Expectation<BankIndexer>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                //every refusal: fail_response sets failed and names the handler in place
                if (data.Failed && "bank".EqualsI(data.Place!))
                    source.TrySetResult($"Failed to deposit item {item.Name}. ({data.ResponseType})");

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    source.TrySetResult($"Failed to deposit item {item.Name}. (not in bank)");
                else if (data.Bank.TryGetValue(bankPack.Value, out var bankedItems))
                {
                    //an explicit slot swaps, so the inventory slot is empty only when the target was. Compared by
                    //name, level and quantity, since prefixes compare by reference
                    if (namedSlot)
                    {
                        var bankedItem = bankSlot.Value < bankedItems.Count ? bankedItems[bankSlot.Value] : null;
                        var inventoryItem = inventorySlot < data.Inventory.Count ? data.Inventory[inventorySlot] : null;

                        if (bankedItem is null
                            || !bankedItem.Name.EqualsI(item.Name)
                            || (bankedItem.Level != item.Level)
                            || (bankedItem.Quantity < item.Quantity))
                            return TaskCache.FALSE;

                        if (occupant is null)
                        {
                            if (inventoryItem is not null)
                                return TaskCache.FALSE;
                        } else if (inventoryItem is null
                                   || !inventoryItem.Name.EqualsI(occupant.Name)
                                   || (inventoryItem.Level != occupant.Level)
                                   || (inventoryItem.Quantity != occupant.Quantity))
                            return TaskCache.FALSE;

                        source.TrySetResult(
                            new BankIndexer
                            {
                                BankPack = bankPack.Value,
                                Index = bankSlot.Value,
                                Item = bankedItem
                            });
                    } else if ((inventorySlot < data.Inventory.Count) && (data.Inventory[inventorySlot] == null))
                    {
                        var probableIndex = bankedItems.FindIndex(b
                            => (b != null) && b.Name.EqualsI(item.Name) && (b.Level == item.Level) && (b.Quantity >= item.Quantity));

                        if (probableIndex == -1)
                            return TaskCache.FALSE;

                        var bankedItem = bankedItems[probableIndex]!;

                        source.TrySetResult(
                            new BankIndexer
                            {
                                BankPack = bankPack.Value,
                                Index = probableIndex,
                                Item = bankedItem
                            });
                    }
                }

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "swap",
                inv = inventorySlot,
                str = bankSlot.Value,
                pack = bankPack.Value
                               .ToString()
                               .ToLower()
            });

        return await source.Task.WithNetworkTimeout();
    }

    /// <summary>Asynchronously equips an item in a slot.</summary>
    /// <param name="inventorySlot">The slot in the inventory of the item to equip.</param>
    /// <param name="slot">The slot to equip the item into.</param>
    /// <exception cref="InvalidOperationException">
    ///     Failed to equip item {itemNameOrSlot}. ({reason})
    /// </exception>
    public async Task EquipAsync(int inventorySlot, Slot slot)
    {
        var item = Character.Inventory[inventorySlot];

        if (item == null)
            throw new InvalidOperationException($"Failed to equip item {inventorySlot}. (slot is empty)");

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var disappearingTextCallback = Socket.On<DisappearingTextData>(
            ALSocketMessageType.DisappearingText,
            data =>
            {
                //Name is the receiver, since an anchorless disappearing_text carries no id
                if (Name.EqualsI(data.Id!) && data.Message.EqualsI("can't equip"))
                    source.TrySetResult($"Failed to equip item {item.Name}. (wrong slot)");

                return TaskCache.FALSE;
            });

        //every equip refusal is a game_response with place "equip"; a gear swap keeps an unequip in flight beside it
        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                //the literal is the receiver, since Place can be null
                if (!data.Failed || !"equip".EqualsI(data.Place!))
                    return TaskCache.FALSE;

                switch (data.ResponseType)
                {
                    case GameResponseType.Invalid:
                        source.TrySetResult($"Failed to equip item {item.Name}. (invalid inventory index)");

                        break;
                    case GameResponseType.NoItem:
                        source.TrySetResult($"Failed to equip item {item.Name}. (no item at index)");

                        break;
                    case GameResponseType.ItemBlocked:
                        source.TrySetResult($"Failed to equip item {item.Name}. (item is blocked)");

                        break;
                    case GameResponseType.ItemPlaceholder:
                        source.TrySetResult($"Failed to equip item {item.Name}. (item is an upgrade placeholder)");

                        break;
                    case GameResponseType.ItemLocked:
                        source.TrySetResult($"Failed to equip item {item.Name}. (item is locked)");

                        break;
                    case GameResponseType.CantEquip:
                        source.TrySetResult(
                            $"Failed to equip item {item.Name}. (cant_equip - wrong class or slot, or a doublehand while the offhand is on)");

                        break;
                }

                return TaskCache.FALSE;
            });

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                var slotItem = data.Slots[slot];

                if ((slotItem != null) && slotItem.Name.EqualsI(item.Name) && (slotItem.Level == item.Level))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Equip,
            new
            {
                num = inventorySlot,
                slot
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>Asynchronously attempts to exchange an item.</summary>
    /// <param name="inventorySlot">The index of the item to exchange.</param>
    /// <returns>
    ///     What the server announced the exchange paid. Empty items and zero gold when it paid nothing, shells or a cx.
    /// </returns>
    /// <exception cref="InvalidOperationException">Failed to exchange. ({reason})</exception>
    public async Task<ExchangeResult> ExchangeAsync(int inventorySlot)
    {
        if (inventorySlot >= Character.InventorySize)
            throw new InvalidOperationException("Failed to exchange. (index out of range)");

        var item = Character.Inventory[inventorySlot];

        if (item == null)
            throw new InvalidOperationException("Failed to exchange. (no item at index)");

        var itemData = item.GetData();

        if (itemData == null)
            throw new InvalidOperationException("Failed to exchange. (no data, contact me)");

        //exchangeability is the count alone; ExchangeAtNPC is missing for most exchangeables
        if (!itemData.ExchangeCount.HasValue)
            throw new InvalidOperationException("Failed to exchange. (item not exchangeable)");

        if (itemData.ExchangeCount > item.Quantity)
            throw new InvalidOperationException($"Failed to exchange. (you do not have {itemData.ExchangeCount})");

        var consumedCount = itemData.ExchangeCount.Value;

        //name/level/qty before the emit — Item references stay readable after ShallowMerge replaces Inventory
        var before = Character.Inventory.ToList();

        var source = new TaskCompletionSource<Expectation<ExchangeResult>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.ExchangeNotEnough => source.TrySetResult(
                        $"Failed to exchange. (youd to not have {itemData.ExchangeCount})"),
                    GameResponseType.Distance when "exchange".EqualsI(data.Place!) => source.TrySetResult(
                        "Failed to exchange. (get closer)"),
                    GameResponseType.ExchangeExisting => source.TrySetResult("Failed to exchange. (already exchanging)"),
                    GameResponseType.CantInBank       => source.TrySetResult("Failed to exchange. (can't exchange from bank)"),
                    _ when data.Failed && "exchange".EqualsI(data.Place!) => source.TrySetResult(
                        $"Failed to exchange. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        var payoutLogs = new List<GameMessageData>();

        using var gameLogCallback = Socket.On<GameMessageData>(
            ALSocketMessageType.GameLog,
            data =>
            {
                payoutLogs.Add(data);

                return TaskCache.FALSE;
            });

        var exchangeStarted = false;

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (!exchangeStarted
                    && (data.QueuedActions?.Exchange != null)
                    && data.QueuedActions.Exchange.CurrentMS.IsNear(data.QueuedActions.Exchange.LengthMS, CORE_CONSTANTS.EPSILON))
                    exchangeStarted = true;

                //the server logs the payout and sends this frame in the tick that finishes the exchange, so only the logs
                //since the previous frame are the exchange's
                if (data.QueuedActions?.Exchange != null)
                {
                    payoutLogs.Clear();

                    return TaskCache.FALSE;
                }

                if (exchangeStarted)
                    source.TrySetResult(
                        ReadExchangePayout(
                            payoutLogs,
                            before,
                            inventorySlot,
                            consumedCount));

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Exchange,
            new
            {
                item_num = inventorySlot,
                q = itemData.ExchangeCount
            });

        return await source.Task.WithTimeout(60000);
    }

    /// <summary>
    ///     Reads what an exchange paid from the payout logs the server sent with the frame that finished it. The logs name
    ///     what was paid, and the inventory supplies the item key, level and slot.
    /// </summary>
    /// <param name="payoutLogs">
    ///     The <c>game_log</c> frames received since the previous character frame.
    /// </param>
    /// <param name="before">The inventory as it stood before the exchange.</param>
    /// <param name="consumedSlot">The inventory slot of the exchanged item.</param>
    /// <param name="consumedCount">
    ///     How many of the exchanged item the exchange consumed.
    /// </param>
    /// <returns>The items and gold the exchange paid.</returns>
    private ExchangeResult ReadExchangePayout(
        IReadOnlyList<GameMessageData> payoutLogs,
        IReadOnlyList<Item?> before,
        int consumedSlot,
        int consumedCount)
    {
        //gold paid by an exchange, a stand sale or a trade
        const string RECEIVED_GOLD_PHRASE = "server.game_log.received_gold";

        //an item only an exchange pays, followed by a, an or many
        const string RECEIVED_ITEM_PHRASE_PREFIX = "server.item.received.";

        var items = new List<InventoryIndexer>();
        long gold = 0;

        foreach (var log in payoutLogs)
        {
            if (log is { Phrase: RECEIVED_GOLD_PHRASE, PhraseArgs: { } goldArgs })
            {
                if (goldArgs["amount"]
                        ?.ToString() is { } amount
                    && long.TryParse(
                        amount,
                        NumberStyles.AllowThousands,
                        CultureInfo.InvariantCulture,
                        out var parsed))
                    gold += parsed;

                continue;
            }

            if ((log.Phrase?.StartsWithI(RECEIVED_ITEM_PHRASE_PREFIX) != true) || log.PhraseArgs is not { } itemArgs)
                continue;

            var announcedName = itemArgs["item"]
                ?.ToString();

            var quantity = itemArgs["quantity"]
                               ?.GetValue<int>()
                           ?? 1;

            if (string.IsNullOrEmpty(announcedName))
                continue;

            var prize = Character.Inventory.FindExchangePrize(
                before,
                consumedSlot,
                consumedCount,
                candidate => IsAnnouncedItem(candidate, announcedName, quantity));

            if (prize is null)
            {
                Logger.Warn($"Exchange paid \"{announcedName}\" x{quantity}, but no inventory slot gained it.");

                continue;
            }

            items.Add(
                prize with
                {
                    Item = prize.Item with
                    {
                        Quantity = quantity
                    }
                });
        }

        return new ExchangeResult(items, gold);
    }

    /// <summary>
    ///     Determines whether an item is the one a payout log named, rendered the way the server names it.
    /// </summary>
    /// <param name="item">The inventory item to test.</param>
    /// <param name="announcedName">
    ///     The display name the log carried: title-cased property and <c>+level</c> for a single item, the bare name for a
    ///     stack.
    /// </param>
    /// <param name="quantity">The quantity the log carried.</param>
    /// <returns>
    ///     <c>true</c> if the item renders as the announced name; otherwise, <c>false</c>.
    /// </returns>
    internal static bool IsAnnouncedItem(Item item, string announcedName, int quantity)
    {
        if (item.GetData() is not { } data)
            return false;

        if (quantity > 1)
            return data.Name == announcedName;

        var rendered = data.Name;

        if (item.Prediction?.Title is { Length: > 0 } title)
            rendered = char.ToUpperInvariant(title[0])
                       + title[1..]
                           .ToLowerInvariant()
                       + " "
                       + rendered;

        if (item.Level > 0)
            rendered += " +" + item.Level;

        return rendered == announcedName;
    }


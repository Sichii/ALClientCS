    /// <summary>
    ///     Asynchronously moves to an number of locations that may or may not require complex pathfinding, with town
    ///     recall suppressed on one map.
    /// </summary>
    /// <param name="endDestinations">
    ///     A collection of potential end locations.
    /// </param>
    /// <param name="useTownIfOptimal">
    ///     Whether or not to consider using town ability. What the caller asked for, kept whole across a refusal.
    /// </param>
    /// <param name="townBlockedOn">
    ///     The map a recall was just refused on, or null. The server refuses one while more than five things are
    ///     targeting the character, which is a fact about standing here rather than about the trip - so it is the map
    ///     that carries the suppression, and leaving it brings the option back.
    /// </param>
    /// <param name="cancellationToken">
    ///     A token used to cancel this action.
    /// </param>
    private async Task SmartMoveAsync<T>(
        IEnumerable<T> endDestinations,
        bool useTownIfOptimal,
        string? townBlockedOn,
        CancellationToken? cancellationToken) where T: ILocation, ICircle
    {
        if (endDestinations.Equals(default))
            throw new ArgumentNullException(nameof(endDestinations));

        // ReSharper disable once SwitchExpressionHandlesSomeKnownEnumValuesWithExceptionInDefault
        Task HandlePathConnectorAsync(GraphEdge pathConnector, CancellationToken? innerToken = null)
            => pathConnector.Type switch
            {
                EdgeType.Walk      => MoveAsync(pathConnector.End.Vertex, innerToken),
                EdgeType.Town      => UseTownAsync(innerToken),
                EdgeType.Leave     => LeaveMapAsync(),
                EdgeType.Door      => TransportAsync(pathConnector.End.Vertex.Map, ((Exit)pathConnector.Start.Vertex).ToSpawnIndex),
                EdgeType.Transport => TransportAsync(pathConnector.End.Vertex.Map, ((Exit)pathConnector.Start.Vertex).ToSpawnIndex),
                _                  => throw new ArgumentOutOfRangeException($"Unexpected path connectorType: {pathConnector.Type}")
            };

        var ends = endDestinations.ToArray();

        if (ends.Length == 0)
            throw new ArgumentNullException(nameof(endDestinations));

        var start = Character.ToLocation();

        //a town connector is only ever added at the path's start node, so whether recall is on the table is decided
        //once, here, and only against the map being left
        var path = Pathfinder.FindPathAsync(start, ends, useTownIfOptimal && (townBlockedOn?.EqualsI(start.Map) != true));

        //a walk that neither throws nor arrives is otherwise indistinguishable from one that never started: both of
        //the silent exits below are ordinary, and a caller only ever sees this method return
        var edgesWalked = 0;

        //the start of the leg last walked, for the bend guard below. Null after anything that is not a walk, since
        //a door or a recall leaves the character somewhere no previous leg leads out of
        ILocation? bendFrom = null;

        await foreach (var edge in path)
        {
            if (cancellationToken is { IsCancellationRequested: true })
                break;

            try
            {
                //a leg ends on a dead-reckoned timer rather than on the server confirming it, and a move that
                //arrives mid-walk is re-aimed from wherever the server actually is - start_moving_element takes
                //from_x off the player rather than off the emit, and the move handler hashes only the two endpoints
                //without tracing between them. So an emit landing early bends the walk from part-way along the
                //previous leg straight to this vertex, which is a line the search never validated: around a corner
                //it is the corner the path was routed around, walked through. Standing still for a round trip is
                //what makes the bend impossible, and it is only paid where the bend would cross something - open
                //ground, which is most of every path, tests clear and waits for nothing.
                //Two of them rather than one, because the trip has to be cleared by the emit and the jitter between
                //a fast trip and a typical one is what the multiplier absorbs - the same shape as the correction
                //grace above
                if ((edge.Type == EdgeType.Walk) && (bendFrom is not null) && !Pathfinder.CanMove(bendFrom, edge.End.Vertex))
                    await Task.Delay(PingManager.LowPercentileOffset * 2, cancellationToken ?? CancellationToken.None);

                await HandlePathConnectorAsync(edge, cancellationToken);
                edgesWalked++;
                bendFrom = edge.Type == EdgeType.Walk ? edge.Start.Vertex : null;
            } catch (OperationCanceledException)
            {
                break;
            } catch (Exception e) when (e is InvalidOperationException or TimeoutException)
            {
                Logger.Debug($"Path leg {edge.Type} to {edge.End.Vertex} failed after {edgesWalked} leg(s). {e.Message}");

                //the rest of the trip is walked, but the refusal is only carried as far as this map. A recall that
                //timed out is carried the same way as one that was refused: the confirmation is the only thing
                //missing either way, and abandoning the trip over it leaves the character where it started
                if ((edge.Type == EdgeType.Town) || e.Message.ContainsI("failed to town"))
                    await SmartMoveAsync(ends, useTownIfOptimal, Character.Map, cancellationToken);

                break;
            }

            //whatever was targeting the character is gone with the map, so recall is worth planning around again -
            //and the path in hand was planned without it, so getting the option back means planning again
            if (townBlockedOn?.EqualsI(Character.Map) == false)
            {
                await SmartMoveAsync(ends, useTownIfOptimal, townBlockedOn: null, cancellationToken);

                return;
            }
        }

        if (edgesWalked == 0)
            Logger.Debug($"No path walked from {start} to {string.Join(", ", ends.Select(end => end.ToString()))}.");
    }


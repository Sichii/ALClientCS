    /// <summary>
    ///     Asynchronously subscribes, emits, and awaits the first matching message.
    /// </summary>
    /// <typeparam name="T">The message's data type.</typeparam>
    /// <param name="messageType">The message to await.</param>
    /// <param name="emitType">The emit to send.</param>
    /// <param name="emitData">The emit's payload, if any.</param>
    /// <param name="handled">
    ///     Specifies whether the message chain stops at this subscriber, which only a request that owns its message type may
    ///     do.
    /// </param>
    /// <param name="timeoutMS">The timeout, or null for the network timeout.</param>
    /// <param name="caller">The calling member, named in a timeout.</param>
    /// <returns>The first matching message.</returns>
    private async Task<Expectation<T>> RequestAsync<T>(
        ALSocketMessageType messageType,
        ALSocketEmitType emitType,
        object? emitData = null,
        bool handled = true,
        int? timeoutMS = null,
        [CallerMemberName] string? caller = null)
    {
        var source = new TaskCompletionSource<Expectation<T>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var callback = Socket.On<T>(
            messageType,
            data =>
            {
                var result = source.TrySetResult(new Expectation<T>(data));

                return handled ? Task.FromResult(result) : TaskCache.FALSE;
            });

        if (emitData == null)
            await Socket.EmitAsync(emitType);
        else
            await Socket.EmitAsync(emitType, emitData);

        return timeoutMS.HasValue ? await source.Task.WithTimeout(timeoutMS.Value) : await source.Task.WithNetworkTimeout(caller);
    }

    /// <summary>
    ///     Asynchronously consumes a potion or regen. The server acknowledges it with an <c>eval</c> carrying the shared pot
    ///     cooldown, and refuses it with a failed <c>game_response</c>.
    /// </summary>
    /// <param name="emitType">The emit to send.</param>
    /// <param name="emitData">The emit's payload.</param>
    /// <param name="description">The item's name in a failure.</param>
    /// <param name="caller">The calling member, named in a timeout.</param>
    /// <exception cref="InvalidOperationException">Failed to use {description}. ({reason})</exception>
    private async Task ConsumeAsync(
        ALSocketEmitType emitType,
        object emitData,
        string description,
        [CallerMemberName] string? caller = null)
    {
        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        //the shared potion cooldown refuses with a not_ready game_response
        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                if (!data.Failed)
                    return TaskCache.FALSE;

                switch (data.ResponseType)
                {
                    case GameResponseType.NotReady:
                        //the server's potion stamp can outlast ours, e.g. after a cave freeze shifts it forward
                        if (data.CooldownMS > 0)
                        {
                            SetCooldown(USE_HP, data.CooldownMS);
                            SetCooldown(USE_MP, data.CooldownMS);
                        }

                        source.TrySetResult($"Failed to use {description}. (not ready for another {data.CooldownMS ?? 0:N0}ms)");

                        break;
                    case GameResponseType.ItemLocked:
                        source.TrySetResult($"Failed to use {description}. (item is locked)");

                        break;
                }

                return TaskCache.FALSE;
            });

        using var evalCallback = Socket.On<EvalData>(
            ALSocketMessageType.Eval,
            data =>
            {
                if (!string.IsNullOrEmpty(data.Code) && RegexCache.POT_TIMEOUT.IsMatch(data.Code))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(emitType, emitData);

        var expectation = await source.Task.WithNetworkTimeout(caller);
        expectation.ThrowIfUnsuccessful();
    }


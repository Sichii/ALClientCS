    /// <summary>
    ///     Checks if a target is within range
    /// </summary>
    /// <exception cref="ArgumentOutOfRangeException">
    /// </exception>
    public bool WithinRange(IRectangle target, float range, DistanceType distanceType)
        => distanceType switch
        {
            DistanceType.CenterToCenter => Character.Distance(target) < range,
            DistanceType.EdgeToCenter => Character.EdgeToCenterDistance(target) < range,
            DistanceType.EdgeToEdge => Character.EdgeToEdgeDistance(target) < range,
            _ => throw new ArgumentOutOfRangeException(nameof(distanceType), distanceType, "Invalid distance type")
        };

    /// <summary>
    ///     Checks if a target is within range of a skill.
    /// </summary>
    /// <param name="target">
    ///     A target able to have edge-to-edge distance calculated.
    /// </param>
    /// <param name="skillName">
    ///     The name of the skill.
    /// </param>
    /// <param name="distanceType">
    ///     The type of distance to calculate.
    /// </param>
    /// <returns>
    ///     <see cref="bool" />
    ///     <br />
    ///     <c>
    ///         true
    ///     </c>
    ///     if the target is within range of the skill, otherwise
    ///     <c>
    ///         false
    ///     </c>
    ///     .
    /// </returns>
    /// <exception cref="ArgumentNullException">
    ///     skillName
    /// </exception>
    /// <exception cref="ArgumentNullException">
    ///     target
    /// </exception>
    public bool WithinSkillRange(IRectangle target, string skillName, DistanceType distanceType = DistanceType.EdgeToEdge)
    {
        if (string.IsNullOrEmpty(skillName))
            throw new ArgumentNullException(nameof(skillName));

        ArgumentNullException.ThrowIfNull(target);

        var data = GameData.Skills[skillName];

        if (data == null)
            return false;

        if (data.AffectsParty)
            return true;

        var range = data.Range;

        if (range == 0)
            range = Character.Range;

        if (data.RangeMultiplier.HasValue)
            range *= data.RangeMultiplier.Value;

        range += data.RangeBonus;
        range *= 0.95f; //for safety

        return distanceType switch
        {
            DistanceType.CenterToCenter => Character.Distance(target) < range,
            DistanceType.EdgeToCenter => Character.EdgeToCenterDistance(target) < range,
            DistanceType.EdgeToEdge => Character.EdgeToEdgeDistance(target) < range,
            _ => throw new ArgumentOutOfRangeException(nameof(distanceType), distanceType, "Invalid distance type")
        };
    }

    /// <summary>
    ///     Checks if you are within range of an NPC, using a range depending on the NPC.
    /// </summary>
    /// <param name="npcId">
    ///     The id of the NPC.
    /// </param>
    /// <exception cref="ArgumentNullException">
    ///     npcId
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Missing npc metadata for {npcId}
    /// </exception>
    public bool WithinRangeOfNPC(string npcId)
    {
        if (string.IsNullOrEmpty(npcId))
            throw new ArgumentNullException(nameof(npcId));

        if (!Players.TryGetValue(npcId, out var npc))
            return false;

        var nData = GameData.NPCs[npcId];

        if (nData == null)
            throw new InvalidOperationException($"Missing npc metadata for {npcId}");

        var range = CORE_CONSTANTS.NPC_RANGE;

        if (nData.Role == NPCRole.Transport)
            range = CORE_CONSTANTS.TRANSPORTER_RANGE;

        return Character.EdgeToEdgeDistance(npc)
                        .IsLess(range, CORE_CONSTANTS.EPSILON);
    }

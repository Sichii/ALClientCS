    /// <summary>
    ///     Asynchronously swaps the items between two bank slots, or moves an item from one slot to another.
    /// </summary>
    /// <param name="bankPack">
    ///     The bankpack whose slots are to be swapped.
    /// </param>
    /// <param name="bankSlot1">
    ///     A slot index within the inventory.
    /// </param>
    /// <param name="bankSlot2">
    ///     A slot index within the inventory.
    /// </param>
    /// <exception cref="ArgumentOutOfRangeException">
    ///     bankSlot1
    /// </exception>
    /// <exception cref="ArgumentOutOfRangeException">
    ///     bankSlot2
    /// </exception>
    /// <exception cref="InvalidOperationException">
    ///     Failed to swap bank slots {bankSlot1} and {bankSlot2}. ({reason})
    /// </exception>
    public async Task SwapBankSlotsAsync(BankPack bankPack, int bankSlot1, int bankSlot2)
    {
        if (Character.Bank == null)
            throw new InvalidOperationException($"Failed to swap bank slots {bankSlot1} and {bankSlot2}. (not in bank)");

        if (!Character.Bank.TryGetValue(bankPack, out var bank))
            throw new InvalidOperationException($"Failed to swap bank slots {bankSlot1} and {bankSlot2}. (bank unavailable)");

        if ((bankSlot1 < 0) || (bankSlot1 >= bank.Count))
            throw new ArgumentOutOfRangeException(nameof(bankSlot1));

        if ((bankSlot2 < 0) || (bankSlot2 >= bank.Count))
            throw new ArgumentOutOfRangeException(nameof(bankSlot2));

        var item1 = bank[bankSlot1];
        var item2 = bank[bankSlot2];

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                if (data.Bank == null)
                    return TaskCache.FALSE;

                if (!data.Bank.TryGetValue(bankPack, out var cBank))
                    return TaskCache.FALSE;

                var cItem1 = cBank[bankSlot1];
                var cItem2 = cBank[bankSlot2];

                if ((cItem1 == item2) && (cItem2 == item1))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Bank,
            new
            {
                operation = "move",
                a = bankSlot1,
                b = bankSlot2,
                pack = bankPack
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();
    }

    /// <summary>
    ///     Asynchronously swaps the items between two inventory slots, or moves an item from one slot to another.
    /// </summary>
    /// <param name="inventorySlot1">
    ///     A slot index within the inventory.
    /// </param>
    /// <param name="inventorySlot2">
    ///     A slot index within the inventory.
    /// </param>
    /// <exception cref="ArgumentOutOfRangeException">
    ///     inventorySlot1
    /// </exception>
    /// <exception cref="ArgumentOutOfRangeException">
    ///     inventorySlot2
    /// </exception>
    public async Task SwapInventorySlotsAsync(int inventorySlot1, int inventorySlot2)
    {
        if ((inventorySlot1 < 0) || (inventorySlot1 >= Character.InventorySize))
            throw new ArgumentOutOfRangeException(nameof(inventorySlot1));

        if ((inventorySlot2 < 0) || (inventorySlot2 >= Character.InventorySize))
            throw new ArgumentOutOfRangeException(nameof(inventorySlot2));

        var item1 = Character.Inventory[inventorySlot1];
        var item2 = Character.Inventory[inventorySlot2];

        var source = new TaskCompletionSource<Expectation>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var characterCallback = Socket.On<CharacterData>(
            ALSocketMessageType.Character,
            data =>
            {
                //bounds-checked: a frame carrying a shorter inventory than the one these slots were read from would
                //otherwise throw inside the callback, and the emit is already with the server by then
                if ((data.Inventory == null) || (inventorySlot1 >= data.Inventory.Count) || (inventorySlot2 >= data.Inventory.Count))
                    return TaskCache.FALSE;

                var cItem1 = data.Inventory[inventorySlot1];
                var cItem2 = data.Inventory[inventorySlot2];

                if (Swapped(cItem1, item2) && Swapped(cItem2, item1))
                {
                    source.TrySetResult(Expectation.Success);

                    return TaskCache.FALSE;
                }

                //the server merges rather than swaps when the two stack, landing the whole stack in the first slot
                //and emptying the second (node/server.js:8354). That is this call succeeding, not failing
                if ((item1 != null)
                    && (item2 != null)
                    && (cItem2 == null)
                    && (cItem1 != null)
                    && cItem1.Name.EqualsI(item1.Name)
                    && (cItem1.Quantity == (item1.Quantity + item2.Quantity)))
                    source.TrySetResult(Expectation.Success);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.InventoryMove,
            new
            {
                a = inventorySlot1,
                b = inventorySlot2
            });

        var expectation = await source.Task.WithNetworkTimeout();
        expectation.ThrowIfUnsuccessful();

        //what identifies a slot's contents, and deliberately not Item's own equality: Item is a record, so the
        //synthesized Equals folds in PossiblePrefixes - an IReadOnlyList<string> that EqualityComparer.Default
        //compares by reference. Two deserializations of the same item never share that list, so a whole-item
        //comparison across two frames is false for everything except a pair of nulls, and this call could only ever
        //time out and throw on a swap that had in fact already happened
        static bool Swapped(Item? slot, Item? expected)
            => ((slot == null) == (expected == null))
               && ((slot == null)
                   || (slot.Name.EqualsI(expected!.Name) && (slot.Level == expected.Level) && (slot.Quantity == expected.Quantity)));
    }

    /// <summary>
    ///     Asynchronously transports from the current map to given spawn in the given map.
    /// </summary>
    /// <param name="map">
    ///     The map to transport to.
    /// </param>
    /// <param name="spawnIndex">
    ///     The spawn index on the map to transport to.
    /// </param>
    /// <returns>
    ///     <see cref="NewMapData" />
    ///     <br />
    ///     Information about our location and map after we transport.
    /// </returns>
    public async Task TransportAsync(string map, int spawnIndex)
    {
        var source = new TaskCompletionSource<Expectation<NewMapData>>(TaskCreationOptions.RunContinuationsAsynchronously);

        using var gameResponseCallback = Socket.On<GameResponseData>(
            ALSocketMessageType.GameResponse,
            data =>
            {
                var result = data.ResponseType switch
                {
                    GameResponseType.TransportFailed    => source.TrySetResult("Transport failed. (can't walk, or jailed)"),
                    GameResponseType.CantEnter          => source.TrySetResult("Transport failed. (can't enter)"),
                    GameResponseType.CantEscape         => source.TrySetResult("Transport failed. (can't escape)"),
                    GameResponseType.TransportCantReach => source.TrySetResult("Transport failed. (can't reach)"),
                    _ when data.Failed && "transport".EqualsI(data.Place!) => source.TrySetResult(
                        $"Transport failed. ({data.Reason ?? data.ResponseType.ToString()})"),
                    _ => false
                };

                return Task.FromResult(result);
            });

        using var newMapCallback = Socket.On<NewMapData>(
            ALSocketMessageType.NewMap,
            data =>
            {
                if (data.Map.EqualsI(map))
                    source.TrySetResult(data);

                return TaskCache.FALSE;
            });

        await Socket.EmitAsync(
            ALSocketEmitType.Transport,
            new
            {
                to = map,
                s = spawnIndex
            });

        NewMapData newMap = await source.Task.WithNetworkTimeout();

        //if we're entering a bank, wait for bank data to populate
        var newData = GameData.Maps[newMap.Map];

        if (newData == null)
            return;

        if (newMap.Map.ContainsI("bank") && newData.Mount)
            await WaitForBankAsync();
    }

